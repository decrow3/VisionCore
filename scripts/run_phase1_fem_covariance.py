def run_session(
    subject: str,
    date: str,
    cfg_path: str,
    out_root: Path,
    args: argparse.Namespace,
) -> dict:
    """
    Run Phase 1 analyses for a single session. Returns summary dict.
    """
    session = f"{subject}_{date}"
    logger.info(f"=== Session: {session} ===")
    t0 = time.time()

    dirs = make_output_tree(out_root, session)

    # ------------------------------------------------------------------
    # 1. Load data
    # ------------------------------------------------------------------
    logger.info("  Loading data...")
    try:
        data = load_session(
            subject, date, cfg_path,
            use_cached=args.use_cached_data,
            fixation_degree_radius=args.fixation_radius,
            verbose=args.verbose,
        )
    except Exception as e:
        logger.error(f"  Data loading failed: {e}\n{traceback.format_exc()}")
        return {"session": session, "status": "data_load_failed", "error": str(e)}

    robs = data["robs"]
    dfs = data["dfs"]
    eyepos = data["eyepos"]
    image_ids = data["image_ids"]
    fix_dur = data["fix_dur"]
    bin_ms = data["bin_ms"]
    cids = data["cids"]

    logger.info(
        f"  Shapes: robs={robs.shape}, eyepos={eyepos.shape}, "
        f"image_ids={image_ids.shape}, bin_ms={bin_ms:.2f}"
    )

    # ------------------------------------------------------------------
    # 2. Valid mask and unit selection
    # ------------------------------------------------------------------
    valid_mask = build_valid_mask(robs, dfs, eyepos, image_ids)
    unit_mask, unit_stats = select_primary_units(
        robs, dfs, valid_mask, bin_ms,
        min_rate_hz=args.min_rate_hz,
        min_valid_fraction=args.min_valid_fraction,
    )
    logger.info(
        f"  Units: total={robs.shape[2]}, primary={int(unit_mask.sum())}, "
        f"valid_bins={int(valid_mask.sum())}"
    )

    # ------------------------------------------------------------------
    # 3. Image repeat support and QC
    # ------------------------------------------------------------------
    image_repeat_records = compute_image_repeat_support(image_ids, valid_mask)
    session_qc = compute_session_qc(
        session, robs, eyepos, image_ids, dfs, valid_mask,
        unit_mask, unit_stats, bin_ms, image_repeat_records,
    )
    unit_qc_rows = compute_unit_qc(session, unit_stats, unit_mask, cids)

    # Write QC outputs
    sess_qc_dir = dirs["session_qc"]
    write_csv(sess_qc_dir / "session_qc.csv", [dict_to_csv_row(session_qc)])
    write_csv(sess_qc_dir / "unit_qc.csv", [dict_to_csv_row(r) for r in unit_qc_rows])
    write_csv(sess_qc_dir / "image_repeat_support.csv", image_repeat_records)
    logger.info(f"  QC written to {sess_qc_dir}")

    if args.run_qc_only:
        return {"session": session, "status": "qc_only", "qc": session_qc}

    # ------------------------------------------------------------------
    # 4. LOTO residuals (shared preprocessing for all analyses)
    # ------------------------------------------------------------------
    logger.info("  Computing LOTO residuals...")
    R_resid = compute_loto_residuals(robs, image_ids, valid_mask)
    n_resid_valid = int(np.isfinite(R_resid[:, :, 0]).sum())
    logger.info(f"  LOTO residuals: {n_resid_valid} valid (trial, time) pairs")

    # Write residual metadata
    resid_meta = {
        "session": session,
        "residual_type": "leave_one_trial_out_image_time_mean",
        "n_valid_trial_time_pairs": n_resid_valid,
        "fraction_pairs_with_residual": n_resid_valid / max(valid_mask.sum(), 1),
    }
    write_csv(sess_qc_dir / "residual_metadata.csv", [resid_meta])

    results: dict = {"session": session, "status": "ok", "qc": session_qc}

    # ------------------------------------------------------------------
    # 5. Analysis 1: covariance geometry
    # ------------------------------------------------------------------
    if args.run_covariance_geometry:
        logger.info("  Running Analysis 1: covariance geometry...")
        try:
            geom = run_covariance_geometry(
                session=session,
                R_raw=robs,
                R_resid=R_resid,
                eye=eyepos,
                image_ids=image_ids,
                valid_mask=valid_mask,
                unit_mask=unit_mask,
                model_alignment_base_dir=VISIONCORE_ROOT / "outputs" / "jacobian_predictive_framework",
                n_splits=args.n_splits,
                n_shuffles=args.n_shuffles,
                seed=args.random_seed,
            )
        except Exception as e:
            logger.error(f"  Covariance geometry failed: {e}\n{traceback.format_exc()}")
            geom = {"session_metrics": {"session": session, "status": "failed", "error": str(e)}}

        sess_cov_dir = dirs["session_covariance_geometry"]

        # Write CSV outputs
        sm = geom.get("session_metrics", {})
        write_csv(sess_cov_dir / "covariance_geometry_session_metrics.csv",
                  [dict_to_csv_row(sm)])

        # Eigenspectrum CSVs
        for estimator_key, eigen_key in [
            ("B_emp_regression", "eigenspectrum_b_emp"),
            ("mcfarland", "eigenspectrum_mcfarland"),
        ]:
            eig = geom.get(eigen_key, {})
            evals = eig.get("eigenvalues")
            if evals is not None and len(evals) > 0:
                eig_rows = [
                    {
                        "session": session,
                        "estimator": estimator_key,
                        "pc_index": i + 1,
                        "eigenvalue": float(evals[i]),
                        "variance_fraction": float(evals[i] / evals.sum()),
                        "cumulative_fraction": float(evals[: i + 1].sum() / evals.sum()),
                    }
                    for i in range(len(evals))
                ]
                write_csv(
                    sess_cov_dir / f"eigenspectrum_{estimator_key}.csv",
                    eig_rows,
                )

        # Shared vs image-specific
        svi = geom.get("shared_vs_image_specific", {})
        write_csv(
            sess_cov_dir / "shared_vs_image_specific_metrics.csv",
            [dict_to_csv_row({**svi, "session": session})],
        )

        # Cached model alignment metrics
        model_align = geom.get("model_alignment", {})
        basis_rows = model_align.get("basis_rows", [])
        if basis_rows:
            rows = []
            for r in basis_rows:
                rows.append(dict_to_csv_row({
                    "session": session,
                    **r,
                    "source_path": model_align.get("source_path", ""),
                }))
            write_csv(sess_cov_dir / "model_alignment_metrics.csv", rows)
        else:
            write_csv(
                sess_cov_dir / "model_alignment_metrics.csv",
                [dict_to_csv_row({
                    "session": session,
                    "basis_name": "",
                    "status": model_align.get("status", "not_available"),
                    "source_path": model_align.get("source_path", ""),
                })],
            )

        # Reliability
        rel = geom.get("reliability", {})
        rel_row = {
            "session": session,
            "split_half_subspace_overlap": rel.get("split_half_subspace_overlap"),
            "split_half_b_cosine": rel.get("split_half_b_cosine"),
            "reliability_ceiling": rel.get("reliability_ceiling"),
            "status": rel.get("status"),
            "n_splits": args.n_splits,
        }
        write_csv(sess_cov_dir / "reliability_metrics.csv", [dict_to_csv_row(rel_row)])

        # Control distributions
        ctrl_dir = dirs["session_controls"]
        for ctrl_name, ctrl_key in [
            ("eye_shuffle", "eye_shuffle_control"),
            ("image_shuffle", "image_shuffle_control"),
        ]:
            ctrl = geom.get(ctrl_key, {})
            t2 = ctrl.get("shuffle_top2_fractions")
            if t2 is not None and len(t2) > 0:
                ctrl_rows = [
                    {"session": session, "control": ctrl_name, "shuffle_index": i,
                     "top2_fraction": float(t2[i])}
                    for i in range(len(t2))
                ]
                write_csv(ctrl_dir / f"{ctrl_name}_distribution.csv", ctrl_rows)

        results["covariance_geometry"] = geom

        # ------------------------------------------------------------------
        # Sanity check: empirical bridge reproduction (Section 9.2)
        # ------------------------------------------------------------------
        logger.info("  Running sanity check (empirical bridge reproduction)...")
        R_p = R_resid[:, :, unit_mask]
        sanity_ok, sanity_details = _sanity_check_b_emp(
            R_p, eyepos, valid_mask, n_shuffles=min(args.n_shuffles, 100), seed=args.random_seed
        )
        results["sanity_passed"] = sanity_ok
        results["sanity_details"] = sanity_details
        logger.info(f"  Sanity check: {sanity_details}")

        if not sanity_ok:
            logger.warning(
                "  SANITY CHECK FAILED. Stopping before batch. "
                "Check preprocessing vs prior bridge pipeline."
            )

    # ------------------------------------------------------------------
    # 6. Analysis 2: noise correlations (stub)
    # ------------------------------------------------------------------
    if args.run_noise_correlations:
        logger.info("  Running Analysis 2: noise correlations...")
        try:
            noise = run_noise_correlations(
                session=session,
                R_raw=robs,
                R_resid_psth=R_resid,
                eye=eyepos,
                valid_mask=valid_mask,
                unit_mask=unit_mask,
                seed=args.random_seed,
            )
        except Exception as e:
            logger.error(f"  Noise correlations failed: {e}\\n{traceback.format_exc()}")
            noise = {
                "session_metrics": {"session": session, "status": "failed", "error": str(e)},
                "pair_metrics_rows": [],
                "synthetic_control_rows": [],
                "residual_structure_rows": [],
            }

        sess_noise_dir = dirs["session_noise_correlations"]
        write_csv(
            sess_noise_dir / "noise_correlation_session_metrics.csv",
            [dict_to_csv_row(noise.get("session_metrics", {"session": session, "status": "missing"}))],
        )
        write_csv(
            sess_noise_dir / "noise_correlation_pair_metrics.csv",
            [dict_to_csv_row(r) for r in noise.get("pair_metrics_rows", [])],
        )
        write_csv(
            sess_noise_dir / "synthetic_control_metrics.csv",
            [dict_to_csv_row(r) for r in noise.get("synthetic_control_rows", [])],
        )
        write_csv(
            sess_noise_dir / "residual_correlation_structure.csv",
            [dict_to_csv_row(r) for r in noise.get("residual_structure_rows", [])],
        )
        results["noise_correlations"] = noise

    # ------------------------------------------------------------------
    # 7. Analysis 3: aggregation scaling
    # ------------------------------------------------------------------
    if args.run_aggregation_scaling:
        logger.info("  Running Analysis 3: aggregation scaling...")
        try:
            agg = run_aggregation_scaling(
                session=session,
                R_resid=R_resid,
                eye=eyepos,
                image_ids=image_ids,
                valid_mask=valid_mask,
                unit_mask=unit_mask,
                sampling_unit=args.aggregation_sampling_unit,
                estimator=args.aggregation_estimator,
                seed=args.random_seed,
                n_bootstrap=args.n_splits,
                min_fit_samples=args.aggregation_min_fit_samples,
                run_eye_shuffle_null=True,
            )
        except Exception as e:
            logger.error(f"  Aggregation scaling failed: {e}\\n{traceback.format_exc()}")
            agg = {
                "session_metrics": {"session": session, "status": "failed", "error": str(e)},
                "aggregation_curve_rows": [],
                "reliability_vs_n_rows": [],
                "stage4_comparison_rows": [],
            }

        sess_agg_dir = dirs["session_aggregation_scaling"]
        write_csv(
            sess_agg_dir / "aggregation_scaling_session_metrics.csv",
            [dict_to_csv_row(agg.get("session_metrics", {"session": session, "status": "missing"}))],
        )
        write_csv(
            sess_agg_dir / "aggregation_scaling_curves.csv",
            [dict_to_csv_row(r) for r in agg.get("aggregation_curve_rows", [])],
        )
        write_csv(
            sess_agg_dir / "reliability_vs_n_windows.csv",
            [dict_to_csv_row(r) for r in agg.get("reliability_vs_n_rows", [])],
        )
        write_csv(
            sess_agg_dir / "stage4_comparison_metrics.csv",
            [dict_to_csv_row(r) for r in agg.get("stage4_comparison_rows", [])],
        )
        results["aggregation_scaling"] = agg

    elapsed = time.time() - t0
    logger.info(f"  Session done in {elapsed:.1f}s")
    results["elapsed_s"] = elapsed
    return results


