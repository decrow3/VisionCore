def main() -> int:
    args = _parse_args()

    # Logging
    level = logging.DEBUG if args.verbose else logging.INFO
    logging.basicConfig(
        level=level,
        format="%(asctime)s  %(levelname)-8s  %(message)s",
        datefmt="%H:%M:%S",
    )

    # Resolve paths
    cfg_path = _resolve_config(args.dataset_configs_path)
    out_root = VISIONCORE_ROOT / args.out_dir
    out_root.mkdir(parents=True, exist_ok=True)
    logger.info(f"Output root: {out_root}")
    logger.info(f"Config: {cfg_path}")

    # Top-level dirs
    top_dirs = make_output_tree(out_root)

    # Parse sessions
    sessions: list[tuple[str, str]] = []
    for spec in args.sessions:
        if ":" in spec:
            subject, date = spec.split(":", 1)
        else:
            raise ValueError(f"Session spec must be SUBJECT:DATE, got '{spec}'")
        sessions.append((subject, date))

    # Pilot mode checks
    if args.pilot and len(sessions) > 1:
        logger.error("Pilot mode requires a single session. Use --sessions Allen:2022-02-16")
        return 1

    # Write config
    config_dict = {
        "requested_bin_ms": args.bin_ms,
        "eye_alignment": "linear_interpolation_to_neural_bin_centers",
        "neural_units": "spike_count_or_rate_as_loaded",
        "primary_residual": "leave_one_trial_out_image_time_mean",
        "secondary_residuals": ["raw_rate_normalized", "trial_time_residual"],
        "min_rate_hz": args.min_rate_hz,
        "min_valid_fraction": args.min_valid_fraction,
        "fixation_radius_deg": args.fixation_radius,
        "random_seed": args.random_seed,
        "n_splits": args.n_splits,
        "n_shuffles": args.n_shuffles,
        "aggregation_sampling_unit": args.aggregation_sampling_unit,
        "aggregation_estimator": args.aggregation_estimator,
        "aggregation_min_fit_samples": args.aggregation_min_fit_samples,
        "sessions": [f"{s}:{d}" for s, d in sessions],
        "dataset_configs_path": cfg_path,
        "primary_C_FEM_method": "mcfarland",
        "sensitivity_C_FEM_method": "B_emp_regression",
        "model_alignment_mode": "cached_model_empirical_alignment_summary",
    }
    write_config(top_dirs["configs"] / "phase1_config.yaml", config_dict)

    inventory_rows = _build_model_object_inventory(VISIONCORE_ROOT)
    write_csv(top_dirs["configs"] / "model_object_inventory.csv", inventory_rows)
    write_csv(top_dirs["covariance_geometry"] / "model_object_inventory.csv", inventory_rows)

    # ------------------------------------------------------------------
    # Run sessions
    # ------------------------------------------------------------------
    all_session_qc: list[dict] = []
    all_session_metrics: list[dict] = []
    all_eigenspectrum_records: list[dict] = []
    all_model_alignment_rows: list[dict] = []
    all_noise_session_rows: list[dict] = []
    all_noise_pair_rows: list[dict] = []
    all_noise_synth_rows: list[dict] = []
    all_noise_structure_rows: list[dict] = []
    all_agg_session_rows: list[dict] = []
    all_agg_curve_rows: list[dict] = []
    all_agg_reliability_rows: list[dict] = []
    all_agg_stage4_rows: list[dict] = []
    session_results: dict[str, dict] = {}

    aborted_by_sanity = False
    for subject, date in sessions:
        result = run_session(subject, date, cfg_path, out_root, args)
        session = f"{subject}_{date}"
        session_results[session] = result

        qc = result.get("qc")
        if qc:
            all_session_qc.append(qc)

        if args.run_covariance_geometry and "covariance_geometry" in result:
            geom = result["covariance_geometry"]
            sm = geom.get("session_metrics")
            if sm:
                all_session_metrics.append(sm)

            model_align = geom.get("model_alignment", {})
            basis_rows = model_align.get("basis_rows", [])
            if basis_rows:
                for r in basis_rows:
                    all_model_alignment_rows.append(
                        dict_to_csv_row({
                            "session": session,
                            **r,
                            "source_path": model_align.get("source_path", ""),
                        })
                    )
            else:
                all_model_alignment_rows.append(
                    dict_to_csv_row({
                        "session": session,
                        "basis_name": "",
                        "status": model_align.get("status", "not_available"),
                        "source_path": model_align.get("source_path", ""),
                    })
                )

            # Collect eigenspectrum records for cross-session figure
            for est_key, eigen_key in [
                ("B_emp_regression", "eigenspectrum_b_emp"),
                ("mcfarland", "eigenspectrum_mcfarland"),
            ]:
                eig = geom.get(eigen_key, {})
                evals = eig.get("eigenvalues")
                if evals is not None and len(evals) > 0:
                    all_eigenspectrum_records.append({
                        "session": session,
                        "estimator": est_key,
                        "eigenvalues": evals,
                        **{k: v for k, v in eig.items() if k != "eigenvalues"},
                    })

        if args.run_covariance_geometry and result.get("sanity_passed") is False:
            logger.error(
                "Sanity gate failed for %s. Stopping remaining sessions before batch progression.",
                session,
            )
            aborted_by_sanity = True
            break

        if args.run_noise_correlations and "noise_correlations" in result:
            noise = result["noise_correlations"]
            sm = noise.get("session_metrics")
            if sm:
                all_noise_session_rows.append(sm)
            all_noise_pair_rows.extend(noise.get("pair_metrics_rows", []))
            all_noise_synth_rows.extend(noise.get("synthetic_control_rows", []))
            all_noise_structure_rows.extend(noise.get("residual_structure_rows", []))

        if args.run_aggregation_scaling and "aggregation_scaling" in result:
            agg = result["aggregation_scaling"]
            sm = agg.get("session_metrics")
            if sm:
                all_agg_session_rows.append(sm)
            all_agg_curve_rows.extend(agg.get("aggregation_curve_rows", []))
            all_agg_reliability_rows.extend(agg.get("reliability_vs_n_rows", []))
            all_agg_stage4_rows.extend(agg.get("stage4_comparison_rows", []))

    # ------------------------------------------------------------------
    # Write aggregated QC outputs
    # ------------------------------------------------------------------
    write_csv(top_dirs["qc"] / "session_qc.csv",
              [dict_to_csv_row(r) for r in all_session_qc])

    # ------------------------------------------------------------------
    # Write aggregated covariance geometry outputs
    # ------------------------------------------------------------------
    if args.run_covariance_geometry and all_session_metrics:
        write_csv(
            top_dirs["covariance_geometry"] / "covariance_geometry_session_metrics.csv",
            [dict_to_csv_row(r) for r in all_session_metrics],
        )
        write_csv(
            top_dirs["covariance_geometry"] / "model_alignment_metrics.csv",
            all_model_alignment_rows,
        )

    # ------------------------------------------------------------------
    # Figures
    # ------------------------------------------------------------------
    fig_dir = top_dirs["figures"]

    if all_session_qc:
        figure_session_qc_overview(
            all_session_qc,
            fig_dir / "session_qc_overview.png",
        )
        write_csv(
            fig_dir / "session_qc_overview.csv",
            [dict_to_csv_row(r) for r in all_session_qc],
        )

    if args.run_covariance_geometry and all_eigenspectrum_records:
        figure_eigenspectra_by_session(
            all_eigenspectrum_records,
            fig_dir / "covariance_eigenspectra_by_session.png",
        )

    if args.run_covariance_geometry and all_session_metrics:
        figure_fem_dimensionality_summary(
            all_session_metrics,
            [],
            fig_dir / "fem_covariance_dimensionality_summary.png",
        )
        write_csv(
            fig_dir / "fem_covariance_dimensionality_summary.csv",
            [dict_to_csv_row(r) for r in all_session_metrics],
        )

    # ------------------------------------------------------------------
    # Write aggregated noise-correlation outputs
    # ------------------------------------------------------------------
    if args.run_noise_correlations and all_noise_session_rows:
        write_csv(
            top_dirs["noise_correlations"] / "noise_correlation_session_metrics.csv",
            [dict_to_csv_row(r) for r in all_noise_session_rows],
        )
        write_csv(
            top_dirs["noise_correlations"] / "noise_correlation_pair_metrics.csv",
            [dict_to_csv_row(r) for r in all_noise_pair_rows],
        )
        write_csv(
            top_dirs["noise_correlations"] / "synthetic_control_metrics.csv",
            [dict_to_csv_row(r) for r in all_noise_synth_rows],
        )
        write_csv(
            top_dirs["noise_correlations"] / "residual_correlation_structure.csv",
            [dict_to_csv_row(r) for r in all_noise_structure_rows],
        )

        svi_rows = []
        for r in all_session_metrics:
            svi_rows.append({
                "session": r.get("session"),
                "mean_r2_shared": r.get("mean_r2_shared"),
                "mean_r2_image_specific": r.get("mean_r2_image_specific"),
                "r2_delta_image_vs_shared": r.get("shared_vs_img_r2_delta"),
            })
        figure_shared_vs_image_specific(svi_rows, fig_dir / "shared_vs_image_specific_geometry.png")
        write_csv(fig_dir / "shared_vs_image_specific_geometry.csv",
                  [dict_to_csv_row(r) for r in svi_rows])

        figure_image_shuffle_eye_shuffle_controls(
            all_session_metrics,
            fig_dir / "image_shuffle_eye_shuffle_controls.png",
        )
        write_csv(
            fig_dir / "image_shuffle_eye_shuffle_controls.csv",
            [dict_to_csv_row(r) for r in all_session_metrics],
        )

    # ------------------------------------------------------------------
    # Write aggregated aggregation-scaling outputs
    # ------------------------------------------------------------------
    if args.run_aggregation_scaling and all_agg_session_rows:
        write_csv(
            top_dirs["aggregation_scaling"] / "aggregation_scaling_session_metrics.csv",
            [dict_to_csv_row(r) for r in all_agg_session_rows],
        )
        write_csv(
            top_dirs["aggregation_scaling"] / "aggregation_scaling_curves.csv",
            [dict_to_csv_row(r) for r in all_agg_curve_rows],
        )
        write_csv(
            top_dirs["aggregation_scaling"] / "reliability_vs_n_windows.csv",
            [dict_to_csv_row(r) for r in all_agg_reliability_rows],
        )
        write_csv(
            top_dirs["aggregation_scaling"] / "stage4_comparison_metrics.csv",
            [dict_to_csv_row(r) for r in all_agg_stage4_rows],
        )

        figure_aggregation_scaling_curves(
            all_agg_curve_rows,
            fig_dir / "aggregation_scaling_curves.png",
        )
        write_csv(
            fig_dir / "aggregation_scaling_curves.csv",
            [dict_to_csv_row(r) for r in all_agg_curve_rows],
        )

        figure_aggregation_scaling_summary(
            all_agg_session_rows,
            fig_dir / "aggregation_scaling_summary.png",
        )
        write_csv(
            fig_dir / "aggregation_scaling_summary.csv",
            [dict_to_csv_row(r) for r in all_agg_session_rows],
        )

    # ------------------------------------------------------------------
    # Pilot report
    # ------------------------------------------------------------------
    if args.pilot and len(sessions) == 1:
        subject, date = sessions[0]
        session = f"{subject}_{date}"
        res = session_results.get(session, {})

        geom = res.get("covariance_geometry", {})
        sm = geom.get("session_metrics", {})
        svi = geom.get("shared_vs_image_specific", {})
        rel = geom.get("reliability", {})

        write_pilot_report(
            path=top_dirs["summaries"] / "pilot_phase1_covariance_report.md",
            session=session,
            session_qc=res.get("qc", {}),
            session_metrics=sm,
            shared_vs_img=svi,
            reliability=rel,
            sanity_passed=res.get("sanity_passed", False),
            sanity_details=res.get("sanity_details", "not run"),
        )
        logger.info(f"Pilot report written to {top_dirs['summaries']}")

    # ------------------------------------------------------------------
    # Final status
    # ------------------------------------------------------------------
    n_ok = sum(1 for r in session_results.values() if r.get("status") not in ("data_load_failed",))
    logger.info(f"Done. {n_ok}/{len(sessions)} sessions completed successfully.")
    logger.info(f"Outputs in: {out_root}")

    if args.pilot and len(sessions) == 1:
        res = list(session_results.values())[0]
        sanity_ok = res.get("sanity_passed", None)
        if sanity_ok is False:
            logger.warning(
                "Pilot sanity check FAILED. Do NOT proceed to batch. "
                "Reconcile preprocessing with prior bridge pipeline first."
            )
            return 2
        elif sanity_ok is True:
            logger.info("Pilot sanity check PASSED. Safe to proceed to batch.")

    if aborted_by_sanity:
        return 2

    return 0


if __name__ == "__main__":
    sys.exit(main())
