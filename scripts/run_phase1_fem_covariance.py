# Sanity check: empirical bridge reproduction (Section 9.2)
# ---------------------------------------------------------------------------

def _sanity_check_b_emp(
    R_resid: np.ndarray,
    eye: np.ndarray,
    valid_mask: np.ndarray,
    n_shuffles: int = 200,
    seed: int = 0,
) -> tuple[bool, str]:
    """
    Check that B_emp split-half geometry > eye-permutation null.

    Returns (passed, details_str).
    """
    from scripts.phase1_fem.estimators import fit_b_emp, _top_k_subspace_overlap

    res = fit_b_emp(R_resid, eye, valid_mask)
    if not res["fit_ok"]:
        return False, "B_emp fit failed — cannot perform sanity check"

    # Observed split-half: compare C_eye geometry across random trial halves.
    NT = R_resid.shape[0]
    rng = np.random.default_rng(seed)
    observed_overlaps = []
    n_splits = 100
    for _ in range(n_splits):
        perm = rng.permutation(NT)
        ha, hb = perm[:NT // 2], perm[NT // 2:]
        r_a = fit_b_emp(R_resid[ha], eye[ha], valid_mask[ha])
        r_b = fit_b_emp(R_resid[hb], eye[hb], valid_mask[hb])
        if not (r_a["fit_ok"] and r_b["fit_ok"]):
            continue
        observed_overlaps.append(_top_k_subspace_overlap(r_a["C_eye"], r_b["C_eye"], k=2))

    if not observed_overlaps:
        return False, "Could not compute split-half subspace overlaps"
    obs_median = float(np.median(observed_overlaps))

    # Permutation null: same split-half overlap metric, but with eye traces
    # trial-permuted before fitting each split.
    null_overlaps = []
    for _ in range(n_shuffles):
        perm = rng.permutation(NT)
        ha, hb = perm[:NT // 2], perm[NT // 2:]

        eye_perm_a = eye[rng.permutation(NT)][ha]
        eye_perm_b = eye[rng.permutation(NT)][hb]

        r_a = fit_b_emp(R_resid[ha], eye_perm_a, valid_mask[ha])
        r_b = fit_b_emp(R_resid[hb], eye_perm_b, valid_mask[hb])
        if not (r_a["fit_ok"] and r_b["fit_ok"]):
            continue
        null_overlaps.append(_top_k_subspace_overlap(r_a["C_eye"], r_b["C_eye"], k=2))

    if not null_overlaps:
        return False, "Permutation null empty — cannot perform sanity check"

    null_p95 = float(np.percentile(null_overlaps, 95))
    passed = obs_median > null_p95
    details = (
        f"Split-half C_eye subspace overlap: observed median={obs_median:.4f}, "
        f"eye-permutation p95={null_p95:.4f}, "
        f"n_obs={len(observed_overlaps)}, n_null={len(null_overlaps)} "
        f"→ {'PASS' if passed else 'FAIL'}"
    )
    return passed, details


def _build_model_object_inventory(root: Path) -> list[dict]:
    """
    Inventory known model-object filenames used for model alignment.

    The current pilot path is empirical-only; this inventory is written so
    model-object plumbing can be completed explicitly in a follow-up.
    """
    expected_patterns = [
        "**/B_model*.npz",
        "**/FEM_PCs*.npz",
        "**/model_FEM_covariance*.npz",
        "**/*model_empirical_alignment*/model_empirical_alignment_summary.json",
        "**/model_object_metadata.csv",
    ]
    rows: list[dict] = []
    for pat in expected_patterns:
        matches = sorted(root.glob(pat))
        if matches:
            for m in matches:
                rows.append(
                    {
                        "pattern": pat,
                        "path": str(m.relative_to(root)),
                        "exists": True,
                        "status": "detected",
                        "note": "Used when supported by current Phase 1 model-alignment plumbing",
                    }
                )
        else:
            rows.append(
                {
                    "pattern": pat,
                    "path": "",
                    "exists": False,
                    "status": "not_found",
                    "note": "No cached object found for this pattern",
                }
            )
    return rows


