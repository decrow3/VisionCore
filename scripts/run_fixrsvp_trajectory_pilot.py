def _safe_mean(x: np.ndarray) -> float:
    if x.size == 0:
        return float("nan")
    return float(np.mean(x))


def _session_output_dir(output_root: Path, session_name: str) -> Path:
    out = output_root / session_name
    out.mkdir(parents=True, exist_ok=True)
    for subdir in REQUIRED_SUBDIRS:
        (out / subdir).mkdir(parents=True, exist_ok=True)
    return out


def _write_yaml_like_config(path: Path, cfg: PilotConfig) -> None:
    # Keep this dependency-free and deterministic.
    lines = ["# Auto-generated by run_fixrsvp_trajectory_pilot.py"]
    for key, value in asdict(cfg).items():
        if isinstance(value, bool):
            rendered = "true" if value else "false"
        elif isinstance(value, (int, float)):
            rendered = str(value)
        else:
            rendered = json.dumps(value)
        lines.append(f"{key}: {rendered}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


