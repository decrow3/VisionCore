    _write_stage_status(
        output_dir / "summaries" / "stage_status.csv",
        stage1_complete=stage1_complete,
        stage2_complete=stage2_complete,
        stage3_complete=stage3_complete,
        stage4_complete=stage4_complete,
    )

    summary = {
        "status": "prepared",
        "session_name": session_name,
        "output_dir": str(output_dir),
        "stage0_readiness": readiness,
        "stage0_meta": readiness_meta,
        "stage1": stage1_result,
        "stage2": stage2_result,
        "stage3": stage3_result,
        "representation_reliability_sweep": reliability_result,
        "stage4": stage4_result,
        "recommendation": readiness_meta["recommendation"],
    }
    (output_dir / "summaries" / "pilot_prepare_summary.json").write_text(
        json.dumps(summary, indent=2) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(summary, indent=2))


