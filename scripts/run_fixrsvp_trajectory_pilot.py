def _pairwise_metrics(z: np.ndarray, eye: np.ndarray, pairs: list[tuple[int, int]]) -> dict[str, float]:
    if not pairs:
        return {"n_pairs": 0, "corr": float("nan"), "slope": float("nan")}
    i = np.asarray([p[0] for p in pairs], dtype=np.int64)
    j = np.asarray([p[1] for p in pairs], dtype=np.int64)
    d_neural = np.linalg.norm(z[i] - z[j], axis=1)
    d_eye = np.linalg.norm(eye[i] - eye[j], axis=1)
    valid = np.isfinite(d_neural) & np.isfinite(d_eye)
    if int(np.sum(valid)) < 4:
        return {"n_pairs": int(np.sum(valid)), "corr": float("nan"), "slope": float("nan")}
    x = d_eye[valid]
    y = d_neural[valid]
    if np.std(x) < 1e-12 or np.std(y) < 1e-12:
        corr = float("nan")
        slope = float("nan")
    else:
        corr = float(np.corrcoef(x, y)[0, 1])
        slope = float(np.polyfit(x, y, 1)[0])
    return {"n_pairs": int(np.sum(valid)), "corr": corr, "slope": slope}


def _fit_distance_regression(
    d_neural: np.ndarray,
    d_eye: np.ndarray,
    lag_bins: np.ndarray,
    mean_rate: np.ndarray,
) -> dict[str, float]:
    valid = np.isfinite(d_neural) & np.isfinite(d_eye) & np.isfinite(lag_bins) & np.isfinite(mean_rate)
    if int(np.sum(valid)) < 10:
        return {"n_pairs": int(np.sum(valid)), "beta_d_eye": float("nan"), "r2": float("nan")}
    y = d_neural[valid].astype(np.float64)
    x = np.column_stack(
        [
            np.ones_like(y),
            d_eye[valid].astype(np.float64),
            lag_bins[valid].astype(np.float64),
            mean_rate[valid].astype(np.float64),
        ]
    )
    beta, *_ = np.linalg.lstsq(x, y, rcond=None)
    y_hat = x @ beta
    ss_tot = float(np.sum((y - np.mean(y)) ** 2))
    ss_res = float(np.sum((y - y_hat) ** 2))
    r2 = float(1.0 - (ss_res / ss_tot)) if ss_tot > 1e-12 else float("nan")
    return {"n_pairs": int(y.size), "beta_d_eye": float(beta[1]), "r2": r2}


def _collect_contiguous_same_image_runs(mask: np.ndarray, image_ids: np.ndarray) -> np.ndarray:
    nt, nb = mask.shape
    lengths: list[int] = []
    for tr in range(nt):
        t = 0
        while t < nb:
            if not mask[tr, t]:
                t += 1
                continue
            img = int(image_ids[tr, t])
            st = t
            t += 1
            while t < nb and mask[tr, t] and int(image_ids[tr, t]) == img:
                t += 1
            lengths.append(t - st)
    return np.asarray(lengths, dtype=np.int64)


def _downbin_time_mean(arr: np.ndarray, factor: int) -> np.ndarray:
    if factor <= 1:
        return arr
    nt, nb = arr.shape[:2]
    new_nb = nb // factor
    if new_nb <= 0:
        return arr
    trim = new_nb * factor
    if arr.ndim == 3:
        x = arr[:, :trim, :]
        return np.mean(x.reshape(nt, new_nb, factor, arr.shape[2]), axis=2)
    x2 = arr[:, :trim]
    return np.mean(x2.reshape(nt, new_nb, factor), axis=2)


def _build_trial_time_residual(robs: np.ndarray, valid_bin_mask: np.ndarray) -> np.ndarray:
    resid = np.full_like(robs, np.nan, dtype=np.float32)
    nt, t_bins, _ = robs.shape
    for t in range(t_bins):
        valid_t = valid_bin_mask[:, t]
        tr_idx = np.where(valid_t)[0]
        if tr_idx.size < 2:
            continue
        vals = robs[tr_idx, t, :]
        sum_vals = np.nansum(vals, axis=0)
        counts = np.sum(np.isfinite(vals), axis=0)
        for tr in tr_idx:
            v = robs[tr, t, :]
            num = sum_vals - np.nan_to_num(v, nan=0.0)
            den = counts - np.isfinite(v).astype(np.int32)
            mu_loo = np.divide(num, np.maximum(den, 1), out=np.full_like(v, np.nan), where=den > 0)
            resid[tr, t, :] = v - mu_loo
    return resid


def _zscore_units(robs: np.ndarray, valid_bin_mask: np.ndarray) -> np.ndarray:
    out = np.full_like(robs, np.nan, dtype=np.float32)
    n_units = robs.shape[2]
    for u in range(n_units):
        vals = robs[:, :, u][valid_bin_mask]
        if vals.size < 2:
            continue
        mu = float(np.mean(vals))
        sd = float(np.std(vals))
        if not np.isfinite(sd) or sd < 1e-8:
            continue
        out[:, :, u] = (robs[:, :, u] - mu) / sd
    return out


def _reduce_to_pca(x: np.ndarray, pca_dims: int) -> tuple[np.ndarray, float]:
    x_center = x - np.mean(x, axis=0, keepdims=True)
    _u, svals, vh = np.linalg.svd(x_center, full_matrices=False)
    nd = max(1, min(int(pca_dims), vh.shape[0]))
    z = x_center @ vh[:nd].T
    total_var = float(np.sum(svals * svals)) if svals.size else float("nan")
    sel_var = float(np.sum((svals[:nd] * svals[:nd]))) if svals.size else float("nan")
    reliability = float(sel_var / total_var) if np.isfinite(total_var) and total_var > 0 else float("nan")
    return z, reliability


def _build_representation(
    robs: np.ndarray,
    valid_bin_mask: np.ndarray,
    image_ids: np.ndarray,
    rep_name: str,
) -> np.ndarray:
    if rep_name == "image_time_residual":
        return _build_loto_residual(robs, valid_bin_mask, image_ids)
    if rep_name == "trial_time_residual":
        return _build_trial_time_residual(robs, valid_bin_mask)
    if rep_name == "raw":
        return robs
    if rep_name == "raw_rate_normalized":
        return _zscore_units(robs, valid_bin_mask)
    raise ValueError(f"Unsupported representation: {rep_name}")


def _ridge_fit_map(dp: np.ndarray, dr: np.ndarray, ridge_alpha: float) -> np.ndarray:
    x = dp.astype(np.float64)
    y = dr.astype(np.float64)
    xtx = x.T @ x
    reg = ridge_alpha * np.eye(xtx.shape[0], dtype=np.float64)
    xty = x.T @ y
    b = np.linalg.solve(xtx + reg, xty)  # shape (2, d)
    return b


def _direction_metrics(dr_true: np.ndarray, dr_pred: np.ndarray) -> dict[str, float]:
    if dr_true.size == 0 or dr_pred.size == 0:
        return {
            "n": 0,
            "median_cosine": float("nan"),
            "mean_cosine": float("nan"),
            "median_predicted_fraction": float("nan"),
            "mean_predicted_fraction": float("nan"),
            "r2": float("nan"),
        }
    true_n = np.linalg.norm(dr_true, axis=1)
    pred_n = np.linalg.norm(dr_pred, axis=1)
    denom = np.maximum(true_n * pred_n, 1e-12)
    cos = np.sum(dr_true * dr_pred, axis=1) / denom
    pred_frac = np.sum(dr_true * dr_pred, axis=1) / np.maximum(np.sum(dr_true * dr_true, axis=1), 1e-12)
    valid = np.isfinite(cos) & np.isfinite(pred_frac) & np.isfinite(true_n) & np.isfinite(pred_n)
    if int(np.sum(valid)) == 0:
        return {
            "n": 0,
            "median_cosine": float("nan"),
            "mean_cosine": float("nan"),
            "median_predicted_fraction": float("nan"),
            "mean_predicted_fraction": float("nan"),
            "r2": float("nan"),
        }
    y = dr_true[valid]
    yhat = dr_pred[valid]
    ss_tot = float(np.sum((y - np.mean(y, axis=0, keepdims=True)) ** 2))
    ss_res = float(np.sum((y - yhat) ** 2))
    r2 = float(1.0 - (ss_res / ss_tot)) if ss_tot > 1e-12 else float("nan")
    return {
        "n": int(np.sum(valid)),
        "median_cosine": float(np.median(cos[valid])),
        "mean_cosine": float(np.mean(cos[valid])),
        "median_predicted_fraction": float(np.median(pred_frac[valid])),
        "mean_predicted_fraction": float(np.mean(pred_frac[valid])),
        "r2": r2,
    }


def _flatten_upper_tri(mat: np.ndarray) -> np.ndarray:
    if mat.ndim != 2 or mat.shape[0] != mat.shape[1]:
        return np.asarray([], dtype=np.float64)
    iu = np.triu_indices(mat.shape[0], k=1)
    return mat[iu].astype(np.float64)


def _covariance_similarity(a: np.ndarray, b: np.ndarray) -> float:
    va = _flatten_upper_tri(a)
    vb = _flatten_upper_tri(b)
    if va.size == 0 or vb.size == 0:
        return float("nan")
    valid = np.isfinite(va) & np.isfinite(vb)
    if int(np.sum(valid)) < 4:
        return float("nan")
    xa = va[valid]
    xb = vb[valid]
    if np.std(xa) < 1e-12 or np.std(xb) < 1e-12:
        return float("nan")
    return float(np.corrcoef(xa, xb)[0, 1])


def _subspace_overlap(u_a: np.ndarray, u_b: np.ndarray, k: int = 5) -> float:
    if u_a.ndim != 2 or u_b.ndim != 2:
        return float("nan")
    ka = min(k, u_a.shape[1])
    kb = min(k, u_b.shape[1])
    kk = min(ka, kb)
    if kk <= 0:
        return float("nan")
    ua = u_a[:, :kk]
    ub = u_b[:, :kk]
    m = ua.T @ ub
    s = np.linalg.svd(m, compute_uv=False)
    return float(np.mean(s)) if s.size else float("nan")


def _pairwise_arrays(
    z: np.ndarray,
    eye: np.ndarray,
    mean_rate: np.ndarray,
    pairs: list[tuple[int, int]],
    pair_lags: np.ndarray,
) -> dict[str, np.ndarray]:
    if not pairs:
        return {
            "d_neural": np.asarray([], dtype=np.float64),
            "d_eye": np.asarray([], dtype=np.float64),
            "lag_bins": np.asarray([], dtype=np.float64),
            "mean_rate": np.asarray([], dtype=np.float64),
        }
    i = np.asarray([p[0] for p in pairs], dtype=np.int64)
    j = np.asarray([p[1] for p in pairs], dtype=np.int64)
    d_neural = np.linalg.norm(z[i] - z[j], axis=1)
    d_eye = np.linalg.norm(eye[i] - eye[j], axis=1)
    lag_bins_arr = pair_lags.astype(np.float64)
    mr = 0.5 * (mean_rate[i] + mean_rate[j])
    valid = np.isfinite(d_neural) & np.isfinite(d_eye) & np.isfinite(lag_bins_arr) & np.isfinite(mr)
    return {
        "d_neural": d_neural[valid],
        "d_eye": d_eye[valid],
        "lag_bins": lag_bins_arr[valid],
        "mean_rate": mr[valid],
    }


def _run_stage3_pairwise_geometry(
    data: dict[str, object],
    output_dir: Path,
    bin_s: float,
    exclusion_pre_ms: float,
    exclusion_post_ms: float,
    pca_dims: int,
    max_pairs_per_class: int,
    short_lag_ms: float,
    long_lag_min_ms: float,
    long_lag_max_ms: float,
    min_segments_for_interpretation: int,
    stage2_segment_count: int,
    stage3_mode: str,
    min_same_image_runs_ge_40ms: int,
    min_same_image_runs_ge_60ms: int,
    min_shortlag_pairs: int,
    min_valid_bin_fraction_pairwise: float,
    min_repeat_support_ge2_pairwise: float,
) -> dict[str, Any]:
    rng = np.random.default_rng(0)

    robs = np.asarray(data["robs"], dtype=np.float32)
    eyepos = np.asarray(data["eyepos"], dtype=np.float32)
    image_ids = np.asarray(data["image_ids"], dtype=np.int64)
    trial_ids_data = data.get("trial_ids")
    trial_ids = np.arange(robs.shape[0], dtype=np.int64) if trial_ids_data is None else np.asarray(trial_ids_data, dtype=np.int64)

    valid_bin_mask = np.isfinite(robs).all(axis=2) & np.isfinite(eyepos).all(axis=2) & (image_ids >= 0)
    events, _ = _detect_microsaccades(
        eyepos_xy=eyepos,
        valid_bin_mask=valid_bin_mask,
        image_ids=image_ids,
        trial_ids=trial_ids,
        bin_s=bin_s,
        pre_ms=50.0,
        post_ms=150.0,
        smooth_sigma_bins=1.0,
        speed_percentile=99.5,
        amp_thresh_deg=0.12,
        refrac_ms=20.0,
    )

    pre_bins = max(1, int(round((exclusion_pre_ms / 1000.0) / max(bin_s, 1e-6))))
    post_bins = max(1, int(round((exclusion_post_ms / 1000.0) / max(bin_s, 1e-6))))
    short_lag_bins = max(1, int(round((short_lag_ms / 1000.0) / max(bin_s, 1e-6))))
    long_min_bins = max(short_lag_bins + 1, int(round((long_lag_min_ms / 1000.0) / max(bin_s, 1e-6))))
    long_max_bins = max(long_min_bins + 1, int(round((long_lag_max_ms / 1000.0) / max(bin_s, 1e-6))))

    exclude_mask = np.zeros_like(valid_bin_mask, dtype=bool)
    by_trial_event_bins: dict[int, list[int]] = {}
    for e in events:
        tr = int(e["trial_index"])
        pk = int(e["peak_bin"])
        by_trial_event_bins.setdefault(tr, []).append(pk)
        st = max(0, pk - pre_bins)
        en = min(valid_bin_mask.shape[1], pk + post_bins)
        exclude_mask[tr, st:en] = True

    analysis_mask = valid_bin_mask & (~exclude_mask)
    run_lengths = _collect_contiguous_same_image_runs(analysis_mask, image_ids)
    bins_40 = max(1, int(round((40.0 / 1000.0) / max(bin_s, 1e-6))))
    bins_60 = max(1, int(round((60.0 / 1000.0) / max(bin_s, 1e-6))))
    n_runs_ge_40 = int(np.sum(run_lengths >= bins_40)) if run_lengths.size else 0
    n_runs_ge_60 = int(np.sum(run_lengths >= bins_60)) if run_lengths.size else 0

    # Repeat support for residual stability: image-time cells with at least 2 repeats.
    repeat_counts: list[int] = []
    for t in range(image_ids.shape[1]):
        valid_t = valid_bin_mask[:, t]
        if not np.any(valid_t):
            continue
        ids_t = image_ids[:, t]
        _u, c = np.unique(ids_t[valid_t], return_counts=True)
        repeat_counts.extend(int(v) for v in c)
    repeat_counts_arr = np.asarray(repeat_counts, dtype=np.int64)
    frac_repeat_ge2 = float(np.mean(repeat_counts_arr >= 2)) if repeat_counts_arr.size else float("nan")

    mode = stage3_mode.lower().strip()
    if mode not in {"auto", "strict", "pairwise"}:
        mode = "auto"
    if mode == "auto":
        mode_resolved = "strict" if stage2_segment_count >= min_segments_for_interpretation else "pairwise"
    else:
        mode_resolved = mode

    strict_ok = stage2_segment_count >= min_segments_for_interpretation

    reps: dict[str, tuple[np.ndarray, float]] = {
        "raw_10ms": (robs, bin_s),
        "resid_image_time_10ms": (_build_loto_residual(robs, valid_bin_mask, image_ids), bin_s),
        "resid_trial_time_10ms": (_build_trial_time_residual(robs, valid_bin_mask), bin_s),
        "smoothed10ms": (_nan_gauss_time(robs, sigma_bins=1.0), bin_s),
        "raw_20ms": (_downbin_time_mean(robs, factor=2), bin_s * 2.0),
    }

    if np.any(~np.isfinite(reps["smoothed10ms"][0])):
        reps["smoothed10ms"] = (np.nan_to_num(reps["smoothed10ms"][0], nan=0.0), bin_s)

    pairwise_rows: list[dict[str, Any]] = []
    gating_rows: list[dict[str, Any]] = []

    if mode_resolved == "strict" and not strict_ok:
        rows = [
            {
                "pair_class": "all",
                "representation": "none",
                "metric": "status",
                "value": "disabled_strict_mode_insufficient_segments",
                "n_pairs": 0,
                "status": "disabled",
            }
        ]
        fields = ["pair_class", "representation", "metric", "value", "n_pairs", "status"]
        _write_rows_csv(output_dir / "distance_distance_metrics.csv", rows, fields)
        _write_rows_csv(output_dir / "distance_distance" / "distance_distance_metrics.csv", rows, fields)
        return {
            "stage3_status": "disabled",
            "stage3_mode": mode_resolved,
            "reason": "insufficient_stage2_segments_for_strict_mode",
            "stage2_segment_count": int(stage2_segment_count),
            "min_segments_for_interpretation": int(min_segments_for_interpretation),
        }

    for rep_name, (rep_robs, rep_bin_s) in reps.items():
        rep_valid = np.isfinite(rep_robs).all(axis=2) & np.isfinite(_downbin_time_mean(eyepos, max(1, int(round(rep_bin_s / max(bin_s, 1e-6)))))).all(axis=2)
        rep_img = _downbin_time_mean(image_ids.astype(np.float32), max(1, int(round(rep_bin_s / max(bin_s, 1e-6)))))
        rep_img = np.rint(rep_img).astype(np.int64)
        rep_analysis_mask = rep_valid & (rep_img >= 0)

        if rep_name.startswith("resid_image_time"):
            resid = rep_robs
        elif rep_name.startswith("resid_trial_time"):
            resid = rep_robs
        else:
            resid = rep_robs

        point_mask = rep_analysis_mask & np.isfinite(resid).all(axis=2)
        if not np.any(point_mask):
            continue

        tr_idx, t_idx = np.where(point_mask)
        x = resid[tr_idx, t_idx, :]
        x_center = x - np.mean(x, axis=0, keepdims=True)
        _u, svals, vh = np.linalg.svd(x_center, full_matrices=False)
        nd = max(1, min(int(pca_dims), vh.shape[0]))
        z = x_center @ vh[:nd].T
        rep_eye_full = _downbin_time_mean(eyepos, max(1, int(round(rep_bin_s / max(bin_s, 1e-6)))))
        eye = rep_eye_full[tr_idx, t_idx, :]
        img = rep_img[tr_idx, t_idx]
        mean_rate_point = np.nanmean(rep_robs[tr_idx, t_idx, :], axis=1)

        per_trial_indices: dict[int, np.ndarray] = {}
        for tr in np.unique(tr_idx):
            per_trial_indices[int(tr)] = np.where(tr_idx == tr)[0]

        classes: dict[str, list[tuple[int, int]]] = {
            "same_image_shortlag": [],
            "same_image_longlag": [],
            "across_image": [],
            "across_microsaccade": [],
            "lag_matched_across_image": [],
            "eye_lag_matched_control": [],
        }
        class_lags: dict[str, list[int]] = {k: [] for k in classes.keys()}

        rep_short_lag_bins = max(1, int(round((short_lag_ms / 1000.0) / max(rep_bin_s, 1e-6))))
        rep_long_min_bins = max(rep_short_lag_bins + 1, int(round((long_lag_min_ms / 1000.0) / max(rep_bin_s, 1e-6))))
        rep_long_max_bins = max(rep_long_min_bins + 1, int(round((long_lag_max_ms / 1000.0) / max(rep_bin_s, 1e-6))))

        for tr, idxs in per_trial_indices.items():
            ord_local = np.argsort(t_idx[idxs])
            idxs = idxs[ord_local]
            times = t_idx[idxs]
            imgs = img[idxs]
            trial_events = sorted(by_trial_event_bins.get(int(tr), []))
            for a in range(len(idxs)):
                for b in range(a + 1, len(idxs)):
                    lag = int(times[b] - times[a])
                    if lag <= 0:
                        continue
                    if lag > rep_long_max_bins:
                        break
                    pa = int(idxs[a])
                    pb = int(idxs[b])
                    same_img = int(imgs[a]) == int(imgs[b])
                    if same_img and lag <= rep_short_lag_bins:
                        classes["same_image_shortlag"].append((pa, pb))
                        class_lags["same_image_shortlag"].append(lag)
                    if same_img and rep_long_min_bins <= lag <= rep_long_max_bins:
                        classes["same_image_longlag"].append((pa, pb))
                        class_lags["same_image_longlag"].append(lag)
                    if (not same_img) and lag <= rep_long_max_bins:
                        classes["across_image"].append((pa, pb))
                        class_lags["across_image"].append(lag)
                    if same_img and trial_events:
                        t0 = int(times[a])
                        t1 = int(times[b])
                        crossed = any((ev > t0) and (ev < t1) for ev in trial_events)
                        if crossed:
                            classes["across_microsaccade"].append((pa, pb))
                            class_lags["across_microsaccade"].append(lag)

        # Build lag-matched across-image control.
        same_pairs = classes["same_image_shortlag"]
        same_lags = np.asarray(class_lags["same_image_shortlag"], dtype=np.int64)
        across_pairs = classes["across_image"]
        across_lags = np.asarray(class_lags["across_image"], dtype=np.int64)
        if same_pairs and len(across_pairs) > 0:
            lag_to_idx: dict[int, np.ndarray] = {}
            if across_lags.size:
                for lag in np.unique(across_lags):
                    lag_to_idx[int(lag)] = np.where(across_lags == lag)[0]
            for lag in same_lags:
                candidates = lag_to_idx.get(int(lag))
                if candidates is None or candidates.size == 0:
                    continue
                pick = int(candidates[int(rng.integers(0, candidates.size))])
                classes["lag_matched_across_image"].append(across_pairs[pick])
                class_lags["lag_matched_across_image"].append(int(lag))

        # Build eye-distance + lag matched control from across-image pairs.
        if same_pairs and classes["lag_matched_across_image"]:
            i_s = np.asarray([p[0] for p in same_pairs], dtype=np.int64)
            j_s = np.asarray([p[1] for p in same_pairs], dtype=np.int64)
            same_d_eye = np.linalg.norm(eye[i_s] - eye[j_s], axis=1)

            lag_ctrl = np.asarray(class_lags["lag_matched_across_image"], dtype=np.int64)
            ctrl_pairs = classes["lag_matched_across_image"]
            i_c = np.asarray([p[0] for p in ctrl_pairs], dtype=np.int64)
            j_c = np.asarray([p[1] for p in ctrl_pairs], dtype=np.int64)
            ctrl_d_eye = np.linalg.norm(eye[i_c] - eye[j_c], axis=1)
            ctrl_bins = np.floor(ctrl_d_eye / 0.02).astype(np.int64)

            by_key: dict[tuple[int, int], list[int]] = {}
            for idx_ctrl, (lag_v, bin_v) in enumerate(zip(lag_ctrl, ctrl_bins)):
                by_key.setdefault((int(lag_v), int(bin_v)), []).append(int(idx_ctrl))

            for lag_v, de in zip(same_lags, same_d_eye):
                key = (int(lag_v), int(np.floor(de / 0.02)))
                cands = by_key.get(key, [])
                if not cands:
                    continue
                pick_local = int(cands[int(rng.integers(0, len(cands)))])
                classes["eye_lag_matched_control"].append(ctrl_pairs[pick_local])
                class_lags["eye_lag_matched_control"].append(int(lag_v))

        for k, v in list(classes.items()):
            if len(v) > max_pairs_per_class:
                sel = rng.choice(len(v), size=max_pairs_per_class, replace=False)
                classes[k] = [v[int(i)] for i in sel]
                class_lags[k] = [class_lags[k][int(i)] for i in sel]

        # Representation reliability proxy: cumulative explained variance in selected PCA dims.
        total_var = float(np.sum(svals * svals)) if svals.size else float("nan")
        sel_var = float(np.sum((svals[:nd] * svals[:nd]))) if svals.size else float("nan")
        rep_reliability = float(sel_var / total_var) if np.isfinite(total_var) and total_var > 0 else float("nan")

        for cls, pairs in classes.items():
            lags = np.asarray(class_lags[cls], dtype=np.float64) if class_lags[cls] else np.asarray([], dtype=np.float64)
            arrs = _pairwise_arrays(
                z=z,
                eye=eye,
                mean_rate=mean_rate_point,
                pairs=pairs,
                pair_lags=lags,
            )
            if arrs["d_neural"].size == 0:
                m = {"n_pairs": 0, "corr": float("nan"), "slope": float("nan")}
            else:
                m = _pairwise_metrics(z, eye, pairs)
            reg = _fit_distance_regression(
                d_neural=arrs["d_neural"],
                d_eye=arrs["d_eye"],
                lag_bins=arrs["lag_bins"],
                mean_rate=arrs["mean_rate"],
            )
            pairwise_rows.append(
                {
                    "pair_class": cls,
                    "representation": rep_name,
                    "metric": "corr",
                    "value": m["corr"],
                    "n_pairs": m["n_pairs"],
                    "status": "ok",
                }
            )
            pairwise_rows.append(
                {
                    "pair_class": cls,
                    "representation": rep_name,
                    "metric": "slope",
                    "value": m["slope"],
                    "n_pairs": m["n_pairs"],
                    "status": "ok",
                }
            )
            pairwise_rows.append(
                {
                    "pair_class": cls,
                    "representation": rep_name,
                    "metric": "reg_beta_d_eye",
                    "value": reg["beta_d_eye"],
                    "n_pairs": reg["n_pairs"],
                    "status": "ok",
                }
            )
            pairwise_rows.append(
                {
                    "pair_class": cls,
                    "representation": rep_name,
                    "metric": "reg_r2",
                    "value": reg["r2"],
                    "n_pairs": reg["n_pairs"],
                    "status": "ok",
                }
            )

            if arrs["d_eye"].size:
                pairwise_rows.append({"pair_class": cls, "representation": rep_name, "metric": "median_lag_bins", "value": float(np.median(arrs["lag_bins"])), "n_pairs": int(arrs["lag_bins"].size), "status": "ok"})
                pairwise_rows.append({"pair_class": cls, "representation": rep_name, "metric": "median_eye_distance_deg", "value": float(np.median(arrs["d_eye"])), "n_pairs": int(arrs["d_eye"].size), "status": "ok"})
                pairwise_rows.append({"pair_class": cls, "representation": rep_name, "metric": "median_neural_distance", "value": float(np.median(arrs["d_neural"])), "n_pairs": int(arrs["d_neural"].size), "status": "ok"})
                pairwise_rows.append({"pair_class": cls, "representation": rep_name, "metric": "eye_distance_range", "value": float(np.nanmax(arrs["d_eye"]) - np.nanmin(arrs["d_eye"])), "n_pairs": int(arrs["d_eye"].size), "status": "ok"})
                pairwise_rows.append({"pair_class": cls, "representation": rep_name, "metric": "neural_distance_range", "value": float(np.nanmax(arrs["d_neural"]) - np.nanmin(arrs["d_neural"])), "n_pairs": int(arrs["d_neural"].size), "status": "ok"})

        pairwise_rows.append({"pair_class": "all", "representation": rep_name, "metric": "representation_reliability", "value": rep_reliability, "n_pairs": int(len(z)), "status": "ok"})

    shortlag_pairs_rep = 0
    for r in pairwise_rows:
        if r.get("pair_class") == "same_image_shortlag" and r.get("metric") == "corr":
            shortlag_pairs_rep = max(shortlag_pairs_rep, int(r.get("n_pairs", 0)))

    gate_checks = {
        "runs_ge_40ms": n_runs_ge_40 >= min_same_image_runs_ge_40ms,
        "runs_ge_60ms": n_runs_ge_60 >= min_same_image_runs_ge_60ms,
        "shortlag_pairs": shortlag_pairs_rep >= min_shortlag_pairs,
        "valid_bin_fraction": float(np.mean(valid_bin_mask)) >= float(min_valid_bin_fraction_pairwise),
        "repeat_support_ge2": bool(np.isfinite(frac_repeat_ge2) and frac_repeat_ge2 >= float(min_repeat_support_ge2_pairwise)),
    }
    gating_rows.extend(
        [
            {"pair_class": "all", "representation": "none", "metric": "gate_runs_ge_40ms", "value": int(gate_checks["runs_ge_40ms"]), "n_pairs": n_runs_ge_40, "status": "ok"},
            {"pair_class": "all", "representation": "none", "metric": "gate_runs_ge_60ms", "value": int(gate_checks["runs_ge_60ms"]), "n_pairs": n_runs_ge_60, "status": "ok"},
            {"pair_class": "all", "representation": "none", "metric": "gate_shortlag_pairs", "value": int(gate_checks["shortlag_pairs"]), "n_pairs": shortlag_pairs_rep, "status": "ok"},
            {"pair_class": "all", "representation": "none", "metric": "gate_valid_bin_fraction", "value": float(np.mean(valid_bin_mask)), "n_pairs": int(np.sum(valid_bin_mask)), "status": "ok"},
            {"pair_class": "all", "representation": "none", "metric": "gate_repeat_support_ge2", "value": frac_repeat_ge2, "n_pairs": int(repeat_counts_arr.size), "status": "ok"},
        ]
    )

    if mode_resolved == "strict":
        stage3_status = "ok"
    else:
        stage3_status = "ok" if all(gate_checks.values()) else "insufficient_pairwise_support"

    rows = pairwise_rows + gating_rows
    rows.append(
        {
            "pair_class": "all",
            "representation": "none",
            "metric": "status",
            "value": stage3_status,
            "n_pairs": int(np.sum([r["n_pairs"] for r in rows if isinstance(r.get("n_pairs"), (int, float))])),
            "status": stage3_status,
        }
    )

    fields = ["pair_class", "representation", "metric", "value", "n_pairs", "status"]
    _write_rows_csv(output_dir / "distance_distance_metrics.csv", rows, fields)
    _write_rows_csv(output_dir / "distance_distance" / "distance_distance_metrics.csv", rows, fields)

    return {
        "stage3_status": stage3_status,
        "stage3_mode": mode_resolved,
        "stage3_role": "diagnostic_qc_only",
        "strict_mode_segment_gate_passed": bool(strict_ok),
        "n_runs_ge_40ms": int(n_runs_ge_40),
        "n_runs_ge_60ms": int(n_runs_ge_60),
        "frac_repeat_support_ge2": float(frac_repeat_ge2),
        "n_pairs_same_image_shortlag": int(shortlag_pairs_rep),
        "min_segments_for_interpretation": int(min_segments_for_interpretation),
        "stage2_segment_count": int(stage2_segment_count),
    }


def _run_representation_reliability_sweep(
    data: dict[str, object],
    output_dir: Path,
    bin_s: float,
    pca_dims: int,
    short_lag_ms: float,
    max_pairs: int,
    min_reliability_for_stage4: float,
) -> dict[str, Any]:
    rng = np.random.default_rng(17)
    robs0 = np.asarray(data["robs"], dtype=np.float32)
    eyepos0 = np.asarray(data["eyepos"], dtype=np.float32)
    image_ids0 = np.asarray(data["image_ids"], dtype=np.int64)

    rows: list[dict[str, Any]] = []
    bin_factors = [1, 2, 4]
    smoothing_modes = ["none", "gaussian"]
    residual_modes = ["image_time_residual", "trial_time_residual", "raw", "raw_rate_normalized"]
    unit_sets = ["all_v1", "high_rate_units"]
    representations = ["pca", "fa_gpfa_unavailable"]

    best = {"reliability": -np.inf, "key": None}

    for bf in bin_factors:
        robs_b = _downbin_time_mean(robs0, bf)
        eye_b = _downbin_time_mean(eyepos0, bf)
        img_b = np.rint(_downbin_time_mean(image_ids0.astype(np.float32), bf)).astype(np.int64)
        bs = bin_s * bf
        short_lag_bins = max(1, int(round((short_lag_ms / 1000.0) / max(bs, 1e-6))))

        for smooth in smoothing_modes:
            robs_s = robs_b if smooth == "none" else _nan_gauss_time(robs_b, sigma_bins=1.0)
            valid_base = np.isfinite(robs_s).all(axis=2) & np.isfinite(eye_b).all(axis=2) & (img_b >= 0)

            unit_rate = np.nanmean(np.where(np.isfinite(robs_s), robs_s, np.nan), axis=(0, 1)) / max(bs, 1e-6)
            finite_rates = unit_rate[np.isfinite(unit_rate)]
            if finite_rates.size == 0:
                high_rate_mask = np.ones(robs_s.shape[2], dtype=bool)
            else:
                high_rate_mask = np.isfinite(unit_rate) & (unit_rate >= np.nanmedian(finite_rates))
            if not np.any(high_rate_mask):
                high_rate_mask = np.ones(robs_s.shape[2], dtype=bool)

            for unit_set in unit_sets:
                if unit_set == "high_rate_units":
                    robs_u = robs_s[:, :, high_rate_mask]
                else:
                    robs_u = robs_s

                valid_u = np.isfinite(robs_u).all(axis=2) & np.isfinite(eye_b).all(axis=2) & (img_b >= 0)

                for resid in residual_modes:
                    rep = _build_representation(robs_u, valid_u, img_b, resid)
                    rep_valid = np.isfinite(rep).all(axis=2) & valid_u
                    if int(np.sum(rep_valid)) < 100:
                        continue

                    tr_idx, t_idx = np.where(rep_valid)
                    x = rep[tr_idx, t_idx, :]
                    z, reliability = _reduce_to_pca(x, pca_dims=pca_dims)
                    eye = eye_b[tr_idx, t_idx, :]
                    img = img_b[tr_idx, t_idx]

                    # Same-image short-lag corr as a diagnostic field.
                    by_trial: dict[int, np.ndarray] = {}
                    for tr in np.unique(tr_idx):
                        by_trial[int(tr)] = np.where(tr_idx == tr)[0]
                    pairs: list[tuple[int, int]] = []
                    for tr, idxs in by_trial.items():
                        ord_local = np.argsort(t_idx[idxs])
                        idxs = idxs[ord_local]
                        tt = t_idx[idxs]
                        ii = img[idxs]
                        for a in range(len(idxs)):
                            for b in range(a + 1, len(idxs)):
                                lag = int(tt[b] - tt[a])
                                if lag <= 0:
                                    continue
                                if lag > short_lag_bins:
                                    break
                                if int(ii[a]) == int(ii[b]):
                                    pairs.append((int(idxs[a]), int(idxs[b])))
                    if len(pairs) > max_pairs:
                        sel = rng.choice(len(pairs), size=max_pairs, replace=False)
                        pairs = [pairs[int(i)] for i in sel]
                    m = _pairwise_metrics(z, eye, pairs)

                    for rep_model in representations:
                        if rep_model == "fa_gpfa_unavailable":
                            rel_val = float("nan")
                            corr_val = float("nan")
                            st4_ready = False
                        else:
                            rel_val = reliability
                            corr_val = m["corr"]
                            st4_ready = bool(np.isfinite(rel_val) and rel_val >= min_reliability_for_stage4)
                        row = {
                            "representation": f"{rep_model}:{resid}",
                            "session": "single_session",
                            "bin_size_ms": int(round(bs * 1000.0)),
                            "smoothing": smooth,
                            "residual_definition": resid,
                            "unit_set": unit_set,
                            "reliability": rel_val,
                            "n_points": int(z.shape[0]) if rep_model == "pca" else 0,
                            "n_units": int(robs_u.shape[2]),
                            "variance_explained_top10": rel_val,
                            "same_image_shortlag_corr": corr_val,
                            "stage4_ready": bool(st4_ready),
                        }
                        rows.append(row)
                        if rep_model == "pca" and np.isfinite(rel_val) and rel_val > best["reliability"]:
                            best = {
                                "reliability": float(rel_val),
                                "key": {
                                    "bin_factor": int(bf),
                                    "bin_size_ms": int(round(bs * 1000.0)),
                                    "smoothing": smooth,
                                    "residual_definition": resid,
                                    "unit_set": unit_set,
                                },
                            }

    fields = [
        "representation",
        "session",
        "bin_size_ms",
        "smoothing",
        "residual_definition",
        "unit_set",
        "reliability",
        "n_points",
        "n_units",
        "variance_explained_top10",
        "same_image_shortlag_corr",
        "stage4_ready",
    ]
    _write_rows_csv(output_dir / "summaries" / "representation_reliability_sweep.csv", rows, fields)
    _write_rows_csv(output_dir / "representation_reliability_sweep.csv", rows, fields)

    return {
        "status": "ok" if rows else "no_rows",
        "n_rows": int(len(rows)),
        "best_representation": best["key"],
        "best_reliability": float(best["reliability"]) if np.isfinite(best["reliability"]) else float("nan"),
        "min_reliability_for_stage4": float(min_reliability_for_stage4),
    }


def _run_stage4_directional_increment(
    data: dict[str, object],
    output_dir: Path,
    bin_s: float,
    pca_dims: int,
    ridge_alpha: float,
    min_points_per_image: int,
    min_reliability_for_stage4: float,
) -> dict[str, Any]:
    rng = np.random.default_rng(23)
    robs0 = np.asarray(data["robs"], dtype=np.float32)
    eye0 = np.asarray(data["eyepos"], dtype=np.float32)
    img0 = np.asarray(data["image_ids"], dtype=np.int64)

    sweep_path = output_dir / "summaries" / "representation_reliability_sweep.csv"
    if not sweep_path.exists():
        return {"status": "skipped", "reason": "missing_reliability_sweep"}

    with sweep_path.open() as f:
        rr = list(csv.DictReader(f))
    pca_rows = [r for r in rr if r.get("representation", "").startswith("pca:")]
    if not pca_rows:
        return {"status": "skipped", "reason": "no_pca_rows_in_sweep"}
    pca_rows_sorted = sorted(
        pca_rows,
        key=lambda r: float(r.get("reliability", "nan")) if r.get("reliability", "") not in ("", "nan") else -np.inf,
        reverse=True,
    )
    best = pca_rows_sorted[0]
    best_rel = float(best.get("reliability", "nan")) if best.get("reliability", "") not in ("", "nan") else float("nan")
    if not np.isfinite(best_rel) or best_rel < float(min_reliability_for_stage4):
        return {
            "status": "skipped",
            "reason": "representation_reliability_below_threshold",
            "best_reliability": best_rel,
            "threshold": float(min_reliability_for_stage4),
        }

    best_bin_ms = int(best["bin_size_ms"])
    bf = max(1, int(round(best_bin_ms / max(bin_s * 1000.0, 1e-6))))
    best_smoothing = best["smoothing"]
    best_resid = best["residual_definition"]
    best_unit_set = best["unit_set"]

    robs_b = _downbin_time_mean(robs0, bf)
    eye_b = _downbin_time_mean(eye0, bf)
    img_b = np.rint(_downbin_time_mean(img0.astype(np.float32), bf)).astype(np.int64)
    bs = bin_s * bf
    robs_s = robs_b if best_smoothing == "none" else _nan_gauss_time(robs_b, sigma_bins=1.0)

    valid_base = np.isfinite(robs_s).all(axis=2) & np.isfinite(eye_b).all(axis=2) & (img_b >= 0)
    unit_rate = np.nanmean(np.where(np.isfinite(robs_s), robs_s, np.nan), axis=(0, 1)) / max(bs, 1e-6)
    finite_rates = unit_rate[np.isfinite(unit_rate)]
    if finite_rates.size == 0:
        high_rate_mask = np.ones(robs_s.shape[2], dtype=bool)
    else:
        high_rate_mask = np.isfinite(unit_rate) & (unit_rate >= np.nanmedian(finite_rates))
    if not np.any(high_rate_mask):
        high_rate_mask = np.ones(robs_s.shape[2], dtype=bool)

    if best_unit_set == "high_rate_units":
        robs_u = robs_s[:, :, high_rate_mask]
    else:
        robs_u = robs_s

    valid_u = np.isfinite(robs_u).all(axis=2) & np.isfinite(eye_b).all(axis=2) & (img_b >= 0)
    rep = _build_representation(robs_u, valid_u, img_b, best_resid)
    rep_valid = np.isfinite(rep).all(axis=2) & valid_u

    # Build same-image consecutive increments.
    points: list[dict[str, Any]] = []
    for tr in range(rep.shape[0]):
        for t in range(rep.shape[1] - 1):
            if not (rep_valid[tr, t] and rep_valid[tr, t + 1]):
                continue
            if int(img_b[tr, t]) != int(img_b[tr, t + 1]):
                continue
            points.append(
                {
                    "trial": int(tr),
                    "time": int(t),
                    "image": int(img_b[tr, t]),
                }
            )
    if len(points) < 200:
        return {"status": "skipped", "reason": "too_few_increment_points", "n_points": int(len(points))}

    # Index arrays
    trials = np.asarray([p["trial"] for p in points], dtype=np.int64)
    times = np.asarray([p["time"] for p in points], dtype=np.int64)
    images = np.asarray([p["image"] for p in points], dtype=np.int64)
    x0 = rep[trials, times, :]
    x1 = rep[trials, times + 1, :]
    dr = x1 - x0
    dp = eye_b[trials, times + 1, :] - eye_b[trials, times, :]
    valid = np.isfinite(dr).all(axis=1) & np.isfinite(dp).all(axis=1)
    trials = trials[valid]
    images = images[valid]
    dr = dr[valid]
    dp = dp[valid]

    z, rep_rel = _reduce_to_pca(x0[valid], pca_dims=pca_dims)
    z_next = _reduce_to_pca(x1[valid], pca_dims=pca_dims)[0]
    dr_lat = z_next - z

    # Global split for pooled shared-map diagnostics.
    tr_unique_global = np.unique(trials)
    sh_trials = rng.permutation(tr_unique_global)
    n_train_trials_global = max(1, int(np.floor(0.7 * sh_trials.size)))
    tr_train_global = set(int(v) for v in sh_trials[:n_train_trials_global])
    tr_test_global = set(int(v) for v in sh_trials[n_train_trials_global:])
    train_global = np.asarray([int(v) in tr_train_global for v in trials], dtype=bool)
    test_global = np.asarray([int(v) in tr_test_global for v in trials], dtype=bool)

    if int(np.sum(train_global)) < 100 or int(np.sum(test_global)) < 100:
        return {
            "status": "skipped",
            "reason": "insufficient_global_train_test_split",
            "n_train": int(np.sum(train_global)),
            "n_test": int(np.sum(test_global)),
        }

    b_shared_global = _ridge_fit_map(dp[train_global], dr_lat[train_global], ridge_alpha=ridge_alpha)

    # Within-image pooled across repeats: held-out by trials per image.
    rows: list[dict[str, Any]] = []
    for img_id in np.unique(images):
        idx = np.where(images == img_id)[0]
        if idx.size < min_points_per_image:
            continue
        train_mask = np.asarray([int(t) in tr_train_global for t in trials[idx]], dtype=bool)
        test_mask = np.asarray([int(t) in tr_test_global for t in trials[idx]], dtype=bool)
        if int(np.sum(train_mask)) < 20 or int(np.sum(test_mask)) < 20:
            continue

        x_tr = dp[idx][train_mask]
        y_tr = dr_lat[idx][train_mask]
        x_te = dp[idx][test_mask]
        y_te = dr_lat[idx][test_mask]

        b_img_only = _ridge_fit_map(x_tr, y_tr, ridge_alpha=ridge_alpha)
        yhat_img_only = x_te @ b_img_only
        m_img_only = _direction_metrics(y_te, yhat_img_only)

        # Shared + image-specific residual map.
        y_tr_shared = x_tr @ b_shared_global
        y_resid = y_tr - y_tr_shared
        b_img_resid = _ridge_fit_map(x_tr, y_resid, ridge_alpha=ridge_alpha)
        yhat = (x_te @ b_shared_global) + (x_te @ b_img_resid)
        m = _direction_metrics(y_te, yhat)

        # Controls
        sh_eye = x_te[rng.permutation(x_te.shape[0])]
        m_eye = _direction_metrics(y_te, (sh_eye @ b_shared_global) + (sh_eye @ b_img_resid))

        wrong_images = [int(v) for v in np.unique(images) if int(v) != int(img_id)]
        if wrong_images:
            img_other = int(wrong_images[int(rng.integers(0, len(wrong_images)))])
            idx_other = np.where(images == img_other)[0]
            if idx_other.size >= min_points_per_image:
                b_other_img_only = _ridge_fit_map(dp[idx_other], dr_lat[idx_other], ridge_alpha=ridge_alpha)
                m_img = _direction_metrics(y_te, x_te @ b_other_img_only)
            else:
                m_img = {"median_cosine": float("nan"), "median_predicted_fraction": float("nan"), "r2": float("nan"), "n": 0, "mean_cosine": float("nan"), "mean_predicted_fraction": float("nan")}
        else:
            m_img = {"median_cosine": float("nan"), "median_predicted_fraction": float("nan"), "r2": float("nan"), "n": 0, "mean_cosine": float("nan"), "mean_predicted_fraction": float("nan")}

        y_tr_shuf = y_tr[rng.permutation(y_tr.shape[0])]
        b_time = _ridge_fit_map(x_tr, y_tr_shuf - (x_tr @ b_shared_global), ridge_alpha=ridge_alpha)
        m_time = _direction_metrics(y_te, (x_te @ b_shared_global) + (x_te @ b_time))

        delta_eye = float(m["median_cosine"] - m_eye["median_cosine"]) if np.isfinite(m["median_cosine"]) and np.isfinite(m_eye["median_cosine"]) else float("nan")
        delta_time = float(m["median_cosine"] - m_time["median_cosine"]) if np.isfinite(m["median_cosine"]) and np.isfinite(m_time["median_cosine"]) else float("nan")

        rows.append(
            {
                "image_id": int(img_id),
                "image_window_id": f"image_{int(img_id)}",
                "metric_scope": "within_image_heldout",
                "model_kind": "shared_plus_image",
                "n_train_points": int(np.sum(train_mask)),
                "n_test": int(m["n"]),
                "n_test_points": int(m["n"]),
                "cosine": m["median_cosine"],
                "predicted_fraction": m["median_predicted_fraction"],
                "median_cosine": m["median_cosine"],
                "median_predicted_fraction": m["median_predicted_fraction"],
                "r2": m["r2"],
                "eye_shuffle_cosine": m_eye["median_cosine"],
                "image_shuffle_cosine": m_img["median_cosine"],
                "time_shuffle_cosine": m_time["median_cosine"],
                "eye_shuffle_median_cosine": m_eye["median_cosine"],
                "image_shuffle_median_cosine": m_img["median_cosine"],
                "time_shuffle_median_cosine": m_time["median_cosine"],
                "delta_cosine_vs_eye_shuffle": delta_eye,
                "delta_cosine_vs_time_shuffle": delta_time,
                "shared_only_cosine": m_img_only["median_cosine"],
            }
        )

        rows.append(
            {
                "image_id": int(img_id),
                "image_window_id": f"image_{int(img_id)}",
                "metric_scope": "within_image_heldout",
                "model_kind": "shared_only",
                "n_train_points": int(np.sum(train_mask)),
                "n_test": int(m_img_only["n"]),
                "n_test_points": int(m_img_only["n"]),
                "cosine": m_img_only["median_cosine"],
                "predicted_fraction": m_img_only["median_predicted_fraction"],
                "median_cosine": m_img_only["median_cosine"],
                "median_predicted_fraction": m_img_only["median_predicted_fraction"],
                "r2": m_img_only["r2"],
                "eye_shuffle_cosine": float("nan"),
                "image_shuffle_cosine": float("nan"),
                "time_shuffle_cosine": float("nan"),
                "eye_shuffle_median_cosine": float("nan"),
                "image_shuffle_median_cosine": float("nan"),
                "time_shuffle_median_cosine": float("nan"),
                "delta_cosine_vs_eye_shuffle": float("nan"),
                "delta_cosine_vs_time_shuffle": float("nan"),
                "shared_only_cosine": m_img_only["median_cosine"],
            }
        )

    # Cross-image generalization
    uniq_img = np.unique(images)
    if uniq_img.size >= 4:
        shimg = rng.permutation(uniq_img)
        n_train_img = max(1, int(np.floor(0.7 * shimg.size)))
        train_imgs = set(int(v) for v in shimg[:n_train_img])
        test_imgs = set(int(v) for v in shimg[n_train_img:])
        train_mask = np.asarray([int(v) in train_imgs for v in images], dtype=bool)
        test_mask = np.asarray([int(v) in test_imgs for v in images], dtype=bool)
        if int(np.sum(train_mask)) >= 50 and int(np.sum(test_mask)) >= 50:
            b_global = _ridge_fit_map(dp[train_mask], dr_lat[train_mask], ridge_alpha=ridge_alpha)
            m_cross = _direction_metrics(dr_lat[test_mask], dp[test_mask] @ b_global)
            m_cross_eye = _direction_metrics(dr_lat[test_mask], dp[test_mask][rng.permutation(int(np.sum(test_mask)))] @ b_global)
            rows.append(
                {
                    "image_id": -1,
                    "image_window_id": "cross_image",
                    "metric_scope": "cross_image_heldout",
                    "model_kind": "shared_only",
                    "n_train_points": int(np.sum(train_mask)),
                    "n_test": int(m_cross["n"]),
                    "n_test_points": int(m_cross["n"]),
                    "cosine": m_cross["median_cosine"],
                    "predicted_fraction": m_cross["median_predicted_fraction"],
                    "median_cosine": m_cross["median_cosine"],
                    "median_predicted_fraction": m_cross["median_predicted_fraction"],
                    "r2": m_cross["r2"],
                    "eye_shuffle_cosine": m_cross_eye["median_cosine"],
                    "image_shuffle_cosine": float("nan"),
                    "time_shuffle_cosine": float("nan"),
                    "eye_shuffle_median_cosine": m_cross_eye["median_cosine"],
                    "image_shuffle_median_cosine": float("nan"),
                    "time_shuffle_median_cosine": float("nan"),
                    "delta_cosine_vs_eye_shuffle": float(m_cross["median_cosine"] - m_cross_eye["median_cosine"]) if np.isfinite(m_cross["median_cosine"]) and np.isfinite(m_cross_eye["median_cosine"]) else float("nan"),
                    "delta_cosine_vs_time_shuffle": float("nan"),
                    "shared_only_cosine": m_cross["median_cosine"],
                }
            )

    # Stage 7-style covariance/subspace checks on selected representation.
    cov_rows: list[dict[str, Any]] = []
    dr_test = dr_lat[test_global]
    dp_test = dp[test_global]
    dr_pred = dp_test @ b_shared_global
    dr_pred_eye_shuf = dp_test[rng.permutation(dp_test.shape[0])] @ b_shared_global
    dr_pred_time_shuf = dr_lat[train_global][rng.permutation(int(np.sum(train_global)))][: dr_test.shape[0]]

    if dr_test.shape[0] >= 10 and dr_pred.shape[0] >= 10:
        cov_true = np.cov(dr_test, rowvar=False)
        cov_pred = np.cov(dr_pred, rowvar=False)
        cov_eye = np.cov(dr_pred_eye_shuf, rowvar=False)
        cov_time = np.cov(dr_pred_time_shuf, rowvar=False)
        cov_rows.extend(
            [
                {"window": "stage4_selected_rep", "metric": "cov_corr_shared_pred", "value": _covariance_similarity(cov_true, cov_pred)},
                {"window": "stage4_selected_rep", "metric": "cov_corr_eye_shuffle", "value": _covariance_similarity(cov_true, cov_eye)},
                {"window": "stage4_selected_rep", "metric": "cov_corr_time_shuffle", "value": _covariance_similarity(cov_true, cov_time)},
            ]
        )

        eval_true, vec_true = np.linalg.eigh(cov_true)
        eval_pred, vec_pred = np.linalg.eigh(cov_pred)
        ord_true = np.argsort(eval_true)[::-1]
        ord_pred = np.argsort(eval_pred)[::-1]
        u_true = vec_true[:, ord_true]
        u_pred = vec_pred[:, ord_pred]
        cov_rows.append(
            {
                "window": "stage4_selected_rep",
                "metric": "top5_subspace_overlap_shared_pred",
                "value": _subspace_overlap(u_true, u_pred, k=5),
            }
        )

    cov_rows.append({"window": "stage4_selected_rep", "metric": "fem_pc_alignment", "value": float("nan")})
    _write_rows_csv(output_dir / "covariance_alignment_metrics.csv", cov_rows, ["window", "metric", "value"])
    _write_rows_csv(output_dir / "covariance" / "covariance_alignment_metrics.csv", cov_rows, ["window", "metric", "value"])

    fields = [
        "image_id",
        "image_window_id",
        "metric_scope",
        "model_kind",
        "n_train_points",
        "n_test",
        "n_test_points",
        "cosine",
        "predicted_fraction",
        "median_cosine",
        "median_predicted_fraction",
        "r2",
        "eye_shuffle_cosine",
        "image_shuffle_cosine",
        "time_shuffle_cosine",
        "eye_shuffle_median_cosine",
        "image_shuffle_median_cosine",
        "time_shuffle_median_cosine",
        "delta_cosine_vs_eye_shuffle",
        "delta_cosine_vs_time_shuffle",
        "shared_only_cosine",
    ]
    _write_rows_csv(output_dir / "increment_metrics.csv", rows, fields)
    _write_rows_csv(output_dir / "increments" / "increment_metrics.csv", rows, fields)

    if rows:
        within_rows = [r for r in rows if r["metric_scope"] == "within_image_heldout" and r.get("model_kind") == "shared_plus_image"]
        if within_rows:
            med_cos = float(np.nanmedian([r["median_cosine"] for r in within_rows]))
            med_pf = float(np.nanmedian([r["median_predicted_fraction"] for r in within_rows]))
            summary_scope = "within_image_heldout"
        else:
            med_cos = float(np.nanmedian([r["median_cosine"] for r in rows]))
            med_pf = float(np.nanmedian([r["median_predicted_fraction"] for r in rows]))
            summary_scope = "fallback_any_scope"
    else:
        med_cos = float("nan")
        med_pf = float("nan")
        summary_scope = "none"

    return {
        "status": "ok" if rows else "no_rows",
        "n_rows": int(len(rows)),
        "selected_representation": {
            "bin_size_ms": int(best_bin_ms),
            "smoothing": best_smoothing,
            "residual_definition": best_resid,
            "unit_set": best_unit_set,
        },
        "selected_representation_reliability": float(best_rel),
        "computed_representation_reliability": float(rep_rel),
        "summary_scope": summary_scope,
        "median_within_image_heldout_cosine": med_cos,
        "median_within_image_predicted_fraction": med_pf,
    }


def _run_stage2_drift_segmentation(
    data: dict[str, object],
    output_dir: Path,
    bin_s: float,
    min_duration_ms: float,
    exclusion_pre_ms: float,
    exclusion_post_ms: float,
) -> dict[str, Any]:
    robs = np.asarray(data["robs"], dtype=np.float32)
    eyepos = np.asarray(data["eyepos"], dtype=np.float32)
    image_ids = np.asarray(data["image_ids"], dtype=np.int64)
    trial_ids_data = data.get("trial_ids")
    trial_ids = np.arange(robs.shape[0], dtype=np.int64) if trial_ids_data is None else np.asarray(trial_ids_data, dtype=np.int64)

    valid_bin_mask = np.isfinite(robs).all(axis=2) & np.isfinite(eyepos).all(axis=2) & (image_ids >= 0)

    # Reuse the same event detector as Stage 1 with fixed defaults unless Stage 1
    # parameters are provided by caller later.
    events, _detect_meta = _detect_microsaccades(
        eyepos_xy=eyepos,
        valid_bin_mask=valid_bin_mask,
        image_ids=image_ids,
        trial_ids=trial_ids,
        bin_s=bin_s,
        pre_ms=50.0,
        post_ms=150.0,
        smooth_sigma_bins=1.0,
        speed_percentile=99.5,
        amp_thresh_deg=0.12,
        refrac_ms=20.0,
    )

    exclude_mask = np.zeros_like(valid_bin_mask, dtype=bool)
    pre_bins = max(1, int(round((exclusion_pre_ms / 1000.0) / max(bin_s, 1e-6))))
    post_bins = max(1, int(round((exclusion_post_ms / 1000.0) / max(bin_s, 1e-6))))
    for e in events:
        tr = int(e["trial_index"])
        pk = int(e["peak_bin"])
        st = max(0, pk - pre_bins)
        en = min(valid_bin_mask.shape[1], pk + post_bins)
        exclude_mask[tr, st:en] = True

    analysis_mask = valid_bin_mask & (~exclude_mask)
    min_bins = max(2, int(round((min_duration_ms / 1000.0) / max(bin_s, 1e-6))))

    by_trial_event_bins: dict[int, list[int]] = {}
    for e in events:
        tr = int(e["trial_index"])
        by_trial_event_bins.setdefault(tr, []).append(int(e["peak_bin"]))

    rows: list[dict[str, Any]] = []
    segment_id = 0
    n_trials, n_bins = analysis_mask.shape
    for tr in range(n_trials):
        t = 0
        while t < n_bins:
            if not analysis_mask[tr, t]:
                t += 1
                continue
            img = int(image_ids[tr, t])
            st = t
            t += 1
            while t < n_bins and analysis_mask[tr, t] and int(image_ids[tr, t]) == img:
                t += 1
            en = t  # exclusive
            seg_len = en - st
            if seg_len < min_bins:
                continue

            pos = eyepos[tr, st:en, :]
            dpos = np.diff(pos, axis=0)
            path_len = float(np.nansum(np.linalg.norm(dpos, axis=1))) if dpos.size else 0.0
            net_disp = float(np.linalg.norm(pos[-1] - pos[0])) if pos.shape[0] > 1 else 0.0
            duration_s = float(seg_len * bin_s)
            mean_speed = float(path_len / duration_s) if duration_s > 0 else float("nan")

            center_bin = 0.5 * (st + en - 1)
            event_bins = by_trial_event_bins.get(tr, [])
            if event_bins:
                nearest_ms = float(np.min(np.abs(np.asarray(event_bins, dtype=np.float64) - center_bin)) * bin_s * 1000.0)
            else:
                nearest_ms = float("nan")

            rows.append(
                {
                    "segment_id": int(segment_id),
                    "trial_id": int(trial_ids[tr]),
                    "image_window_id": f"image_{img}",
                    "start_time_s": float(st * bin_s),
                    "end_time_s": float((en - 1) * bin_s),
                    "duration_ms": float(seg_len * bin_s * 1000.0),
                    "eye_path_length_deg": path_len,
                    "net_eye_displacement_deg": net_disp,
                    "mean_drift_speed_deg_s": mean_speed,
                    "distance_to_nearest_microsaccade_ms": nearest_ms,
                }
            )
            segment_id += 1

    fields = [
        "segment_id",
        "trial_id",
        "image_window_id",
        "start_time_s",
        "end_time_s",
        "duration_ms",
        "eye_path_length_deg",
        "net_eye_displacement_deg",
        "mean_drift_speed_deg_s",
        "distance_to_nearest_microsaccade_ms",
    ]
    _write_rows_csv(output_dir / "drift_segments.csv", rows, fields)
    _write_rows_csv(output_dir / "trajectories" / "drift_segments.csv", rows, fields)

    durations = np.asarray([row["duration_ms"] for row in rows], dtype=np.float64)
    if durations.size:
        plt.figure(figsize=(6, 4))
        plt.hist(durations, bins=30, color="tab:blue", alpha=0.9)
        plt.xlabel("Drift segment duration (ms)")
        plt.ylabel("Count")
        plt.title("Stage 2 drift segment durations")
        plt.tight_layout()
        plt.savefig(output_dir / "trajectories" / "drift_segment_duration_hist.png", dpi=150)
        plt.close()

    return {
        "stage2_status": "ok" if len(rows) > 0 else "no_segments",
        "n_segments": int(len(rows)),
        "median_segment_duration_ms": float(np.median(durations)) if durations.size else float("nan"),
        "p90_segment_duration_ms": float(np.percentile(durations, 90.0)) if durations.size else float("nan"),
        "min_duration_ms": float(min_duration_ms),
        "exclusion_pre_ms": float(exclusion_pre_ms),
        "exclusion_post_ms": float(exclusion_post_ms),
    }


def _write_rows_csv(path: Path, rows: list[dict[str, Any]], fieldnames: list[str]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        if rows:
            writer.writerows(rows)


def _nan_gauss_time(arr: np.ndarray, sigma_bins: float) -> np.ndarray:
    if sigma_bins <= 0:
        return arr
    arr0 = np.where(np.isnan(arr), 0.0, arr)
    w = (~np.isnan(arr)).astype(np.float32)
    f_arr = gaussian_filter1d(arr0, sigma_bins, axis=1, mode="nearest")
    f_w = gaussian_filter1d(w, sigma_bins, axis=1, mode="nearest")
    out = np.divide(f_arr, f_w, out=np.full_like(f_arr, np.nan), where=f_w > 1e-8)
    return out


def _detect_microsaccades(
    eyepos_xy: np.ndarray,
    valid_bin_mask: np.ndarray,
    image_ids: np.ndarray,
    trial_ids: np.ndarray,
    bin_s: float,
    pre_ms: float,
    post_ms: float,
    smooth_sigma_bins: float,
    speed_percentile: float,
    amp_thresh_deg: float,
    refrac_ms: float,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    ex = _nan_gauss_time(eyepos_xy[:, :, 0], smooth_sigma_bins)
    ey = _nan_gauss_time(eyepos_xy[:, :, 1], smooth_sigma_bins)
    dx = np.diff(ex, axis=1)
    dy = np.diff(ey, axis=1)
    speed = np.sqrt(dx * dx + dy * dy) / max(bin_s, 1e-6)
    step_valid = valid_bin_mask[:, 1:] & valid_bin_mask[:, :-1]
    speed_valid = speed[step_valid & np.isfinite(speed)]
    if speed_valid.size == 0:
        return [], {
            "n_detected": 0,
            "speed_threshold_deg_s": float("nan"),
            "pre_bins": 0,
            "post_bins": 0,
        }

    speed_thr = float(np.percentile(speed_valid, speed_percentile))
    pre_bins = max(1, int(round((pre_ms / 1000.0) / bin_s)))
    post_bins = max(1, int(round((post_ms / 1000.0) / bin_s)))
    refrac_bins = max(1, int(round((refrac_ms / 1000.0) / bin_s)))

    events: list[dict[str, Any]] = []
    for tr in range(eyepos_xy.shape[0]):
        s = speed[tr]
        if not np.isfinite(s).any():
            continue
        local_max = (s > np.roll(s, 1)) & (s >= np.roll(s, -1))
        cand = np.where((s >= speed_thr) & local_max)[0]
        cand = cand[(cand >= pre_bins + 1) & (cand < s.shape[0] - post_bins - 1)]
        if cand.size == 0:
            continue

        keep: list[int] = []
        for t0 in cand:
            if keep and (t0 - keep[-1] < refrac_bins):
                continue
            left = t0
            while left > 0 and np.isfinite(s[left]) and s[left] > 0.5 * speed_thr:
                left -= 1
            right = t0
            while right < s.shape[0] - 1 and np.isfinite(s[right]) and s[right] > 0.5 * speed_thr:
                right += 1
            onset_bin = max(left, 0)
            offset_bin = min(right + 1, eyepos_xy.shape[1] - 1)
            if onset_bin >= offset_bin:
                continue
            if not (valid_bin_mask[tr, onset_bin] and valid_bin_mask[tr, offset_bin]):
                continue
            disp = float(np.hypot(ex[tr, offset_bin] - ex[tr, onset_bin], ey[tr, offset_bin] - ey[tr, onset_bin]))
            if not np.isfinite(disp) or disp < amp_thresh_deg:
                continue
            direction = float(np.arctan2(ey[tr, offset_bin] - ey[tr, onset_bin], ex[tr, offset_bin] - ex[tr, onset_bin]))
            peak_bin = int(t0 + 1)
            image_id = int(image_ids[tr, peak_bin]) if peak_bin < image_ids.shape[1] else -1
            events.append(
                {
                    "trial_index": int(tr),
                    "trial_id": int(trial_ids[tr]),
                    "image_id": int(image_id),
                    "onset_bin": int(onset_bin),
                    "peak_bin": int(peak_bin),
                    "offset_bin": int(offset_bin),
                    "onset_time_s": float(onset_bin * bin_s),
                    "peak_velocity_time_s": float(peak_bin * bin_s),
                    "offset_time_s": float(offset_bin * bin_s),
                    "amplitude_deg": float(disp),
                    "direction_rad": direction,
                    "duration_ms": float((offset_bin - onset_bin) * bin_s * 1000.0),
                    "peak_speed_deg_s": float(s[t0]),
                    "valid": True,
                }
            )
            keep.append(int(t0))

    return events, {
        "n_detected": int(len(events)),
        "speed_threshold_deg_s": speed_thr,
        "pre_bins": int(pre_bins),
        "post_bins": int(post_bins),
    }


def _build_loto_residual(robs: np.ndarray, valid_bin_mask: np.ndarray, image_ids: np.ndarray) -> np.ndarray:
    resid = np.full_like(robs, np.nan, dtype=np.float32)
    nt, t_bins, _ = robs.shape
    for t in range(t_bins):
        valid_t = valid_bin_mask[:, t]
        if not np.any(valid_t):
            continue
        imgs = image_ids[:, t]
        for img in np.unique(imgs[valid_t]):
            tr_idx = np.where(valid_t & (imgs == img))[0]
            if tr_idx.size < 2:
                continue
            vals = robs[tr_idx, t, :]
            sum_vals = np.nansum(vals, axis=0)
            counts = np.sum(np.isfinite(vals), axis=0)
            for tr in tr_idx:
                v = robs[tr, t, :]
                num = sum_vals - np.nan_to_num(v, nan=0.0)
                den = counts - np.isfinite(v).astype(np.int32)
                mu_loo = np.divide(num, np.maximum(den, 1), out=np.full_like(v, np.nan), where=den > 0)
                resid[tr, t, :] = v - mu_loo
    return resid


def _run_stage1_transient(
    data: dict[str, object],
    output_dir: Path,
    bin_s: float,
    pre_ms: float,
    post_ms: float,
    smooth_sigma_bins: float,
    speed_percentile: float,
    amp_thresh_deg: float,
    refrac_ms: float,
) -> dict[str, Any]:
    robs = np.asarray(data["robs"], dtype=np.float32)
    eyepos = np.asarray(data["eyepos"], dtype=np.float32)
    image_ids = np.asarray(data["image_ids"], dtype=np.int64)
    trial_ids_data = data.get("trial_ids")
    trial_ids = np.arange(robs.shape[0], dtype=np.int64) if trial_ids_data is None else np.asarray(trial_ids_data, dtype=np.int64)

    valid_bin_mask = np.isfinite(robs).all(axis=2) & np.isfinite(eyepos).all(axis=2) & (image_ids >= 0)
    events, detect_meta = _detect_microsaccades(
        eyepos_xy=eyepos,
        valid_bin_mask=valid_bin_mask,
        image_ids=image_ids,
        trial_ids=trial_ids,
        bin_s=bin_s,
        pre_ms=pre_ms,
        post_ms=post_ms,
        smooth_sigma_bins=smooth_sigma_bins,
        speed_percentile=speed_percentile,
        amp_thresh_deg=amp_thresh_deg,
        refrac_ms=refrac_ms,
    )

    microsaccade_rows = [
        {
            "trial_id": e["trial_id"],
            "image_id": e["image_id"],
            "onset_time_s": e["onset_time_s"],
            "peak_velocity_time_s": e["peak_velocity_time_s"],
            "offset_time_s": e["offset_time_s"],
            "amplitude_deg": e["amplitude_deg"],
            "direction_rad": e["direction_rad"],
            "duration_ms": e["duration_ms"],
            "valid": e["valid"],
        }
        for e in events
    ]

    microsaccade_fields = [
        "trial_id",
        "image_id",
        "onset_time_s",
        "peak_velocity_time_s",
        "offset_time_s",
        "amplitude_deg",
        "direction_rad",
        "duration_ms",
        "valid",
    ]
    _write_rows_csv(output_dir / "microsaccades.csv", microsaccade_rows, microsaccade_fields)
    _write_rows_csv(output_dir / "transient" / "microsaccades.csv", microsaccade_rows, microsaccade_fields)

    pre_bins = detect_meta["pre_bins"]
    post_bins = detect_meta["post_bins"]
    win_len = pre_bins + post_bins
    t_rel_ms = (np.arange(-pre_bins, post_bins, dtype=np.float64) * bin_s * 1000.0).astype(np.float64)

    resid = _build_loto_residual(robs, valid_bin_mask, image_ids)

    raw_windows: list[np.ndarray] = []
    resid_windows: list[np.ndarray] = []
    kept_events = 0
    for e in events:
        tr = int(e["trial_index"])
        pk = int(e["peak_bin"])
        st = pk - pre_bins
        en = pk + post_bins
        if st < 0 or en > robs.shape[1]:
            continue
        rv = robs[tr, st:en, :]
        zv = resid[tr, st:en, :]
        if rv.shape[0] != win_len or zv.shape[0] != win_len:
            continue
        if np.isnan(rv).all() or np.isnan(zv).all():
            continue
        raw_windows.append(rv)
        resid_windows.append(zv)
        kept_events += 1

    if kept_events == 0:
        transient_rows = [
            {"metric": "status", "value": "no_valid_events"},
            {"metric": "n_events_detected", "value": int(len(events))},
            {"metric": "n_events_used", "value": 0},
            {"metric": "recommended_exclusion_pre_ms", "value": float(pre_ms)},
            {"metric": "recommended_exclusion_post_ms", "value": float(post_ms)},
        ]
        _write_rows_csv(output_dir / "transient_metrics.csv", transient_rows, ["metric", "value"])
        _write_rows_csv(output_dir / "transient" / "transient_metrics.csv", transient_rows, ["metric", "value"])
        return {
            "stage1_status": "no_valid_events",
            "n_events_detected": int(len(events)),
            "n_events_used": 0,
        }

    raw_arr = np.stack(raw_windows, axis=0)
    resid_arr = np.stack(resid_windows, axis=0)

    raw_pop = _nanmean_safe(raw_arr, axis=2)
    resid_pop = _nanmean_safe(resid_arr, axis=2)
    raw_psth = _nanmean_safe(raw_pop, axis=0)
    resid_psth = _nanmean_safe(resid_pop, axis=0)

    X = resid_arr.reshape(-1, resid_arr.shape[-1])
    valid_rows = np.isfinite(X).all(axis=1)
    Xv = X[valid_rows]
    Xc = Xv - np.mean(Xv, axis=0, keepdims=True)
    _u, s, vh = np.linalg.svd(Xc, full_matrices=False)
    denom = float(np.sum(s * s)) + 1e-12
    var_expl = (s * s) / denom
    axis1 = vh[0]

    proj = np.tensordot(resid_arr, axis1, axes=([2], [0]))
    proj_mean = np.nanmean(proj, axis=0)
    baseline_mask = t_rel_ms < 0
    baseline_abs = np.abs(proj_mean[baseline_mask]) if np.any(baseline_mask) else np.abs(proj_mean)
    baseline_thr = float(np.mean(baseline_abs) + 2.0 * np.std(baseline_abs)) if baseline_abs.size else 0.0
    post_mask = t_rel_ms >= 0
    post_vals = np.abs(proj_mean[post_mask])
    if post_vals.size:
        peak_idx_post = int(np.argmax(post_vals))
        peak_idx = int(np.where(post_mask)[0][peak_idx_post])
    else:
        peak_idx = int(np.argmax(np.abs(proj_mean)))
    time_to_peak_ms = float(t_rel_ms[peak_idx])

    return_idx = -1
    for i in range(peak_idx, len(proj_mean)):
        if np.abs(proj_mean[i]) <= baseline_thr:
            return_idx = i
            break
    time_to_return_ms = float(t_rel_ms[return_idx]) if return_idx >= 0 else float("nan")

    if np.isfinite(time_to_return_ms):
        rec_post_ms = max(float(post_ms), float(np.ceil((time_to_return_ms + 25.0) / 5.0) * 5.0))
    else:
        rec_post_ms = float(post_ms)

    transient_rows = [
        {"metric": "status", "value": "ok"},
        {"metric": "n_events_detected", "value": int(len(events))},
        {"metric": "n_events_used", "value": int(kept_events)},
        {"metric": "speed_threshold_deg_s", "value": float(detect_meta["speed_threshold_deg_s"])},
        {"metric": "median_microsaccade_amplitude_deg", "value": float(np.median([e["amplitude_deg"] for e in events])) if events else float("nan")},
        {"metric": "median_microsaccade_duration_ms", "value": float(np.median([e["duration_ms"] for e in events])) if events else float("nan")},
        {"metric": "transient_axis_var_explained_pc1", "value": float(var_expl[0]) if var_expl.size > 0 else float("nan")},
        {"metric": "transient_axis_var_explained_pc2", "value": float(var_expl[1]) if var_expl.size > 1 else float("nan")},
        {"metric": "time_to_peak_ms", "value": float(time_to_peak_ms)},
        {"metric": "time_to_return_ms", "value": float(time_to_return_ms)},
        {"metric": "recommended_exclusion_pre_ms", "value": float(pre_ms)},
        {"metric": "recommended_exclusion_post_ms", "value": float(rec_post_ms)},
    ]
    _write_rows_csv(output_dir / "transient_metrics.csv", transient_rows, ["metric", "value"])
    _write_rows_csv(output_dir / "transient" / "transient_metrics.csv", transient_rows, ["metric", "value"])

    plt.figure(figsize=(8, 4))
    plt.plot(t_rel_ms, raw_psth, label="raw", color="black")
    plt.plot(t_rel_ms, resid_psth, label="residual", color="tab:blue")
    plt.axvline(0.0, color="gray", linestyle="--", linewidth=1.0)
    plt.xlabel("Time relative to microsaccade peak (ms)")
    plt.ylabel("Population mean response")
    plt.title("Perimicrosaccadic population PSTH")
    plt.legend(frameon=False)
    plt.tight_layout()
    plt.savefig(output_dir / "transient" / "perimicrosaccadic_population_psth.png", dpi=150)
    plt.close()

    plt.figure(figsize=(8, 4))
    plt.plot(t_rel_ms, proj_mean, color="tab:red")
    plt.axvline(0.0, color="gray", linestyle="--", linewidth=1.0)
    plt.axhline(baseline_thr, color="tab:green", linestyle=":", linewidth=1.0)
    plt.axhline(-baseline_thr, color="tab:green", linestyle=":", linewidth=1.0)
    plt.xlabel("Time relative to microsaccade peak (ms)")
    plt.ylabel("Projection onto transient axis (PC1)")
    plt.title("Transient-axis projection time course")
    plt.tight_layout()
    plt.savefig(output_dir / "transient" / "transient_axis_projection.png", dpi=150)
    plt.close()

    return {
        "stage1_status": "ok",
        "n_events_detected": int(len(events)),
        "n_events_used": int(kept_events),
        "recommended_exclusion_pre_ms": float(pre_ms),
        "recommended_exclusion_post_ms": float(rec_post_ms),
    }


