def _validate_required_keys(data: dict[str, object]) -> None:
    required = ["robs", "eyepos", "image_ids", "fix_dur"]
    missing = [k for k in required if k not in data]
    if missing:
        raise KeyError(f"Missing keys {missing}; available keys: {sorted(data.keys())}")


def _validate_shapes(robs: np.ndarray, eyepos: np.ndarray, image_ids: np.ndarray, fix_dur: np.ndarray) -> None:
    if robs.ndim != 3:
        raise ValueError(f"Expected robs to be 3D (trial,time,unit), got shape {robs.shape}")
    if eyepos.shape[:2] != robs.shape[:2]:
        raise ValueError(
            f"Shape mismatch: eyepos shape {eyepos.shape} does not match robs trial/time {robs.shape[:2]}"
        )
    if image_ids.shape != robs.shape[:2]:
        raise ValueError(
            f"Shape mismatch: image_ids shape {image_ids.shape} does not match robs trial/time {robs.shape[:2]}"
        )
    if fix_dur.shape[0] != robs.shape[0]:
        raise ValueError(
            f"Shape mismatch: fix_dur length {fix_dur.shape[0]} does not match trials {robs.shape[0]}"
        )


def _infer_bin_ms(data: dict[str, object], requested_bin_ms: int) -> tuple[float, str]:
    trial_t_bins = data.get("trial_t_bins")
    if trial_t_bins is None or not isinstance(trial_t_bins, (list, tuple)):
        return float(requested_bin_ms), "requested_fallback_no_trial_t_bins"
    diffs: list[np.ndarray] = []
    for arr in trial_t_bins:
        vec = np.asarray(arr, dtype=np.float64)
        vec = vec[np.isfinite(vec)]
        if vec.size < 3:
            continue
        dv = np.diff(vec)
        dv = dv[(np.isfinite(dv)) & (dv > 0)]
        if dv.size:
            diffs.append(dv)
    if not diffs:
        return float(requested_bin_ms), "requested_fallback_no_valid_diffs"
    all_diffs = np.concatenate(diffs)
    return float(np.median(all_diffs) * 1000.0), "inferred_from_trial_t_bins"


def _collect_same_image_run_lengths(valid_bin_mask: np.ndarray, image_ids: np.ndarray) -> np.ndarray:
    nt, t_bins = image_ids.shape
    run_lengths: list[int] = []
    for tr in range(nt):
        run_len = 0
        prev_img = -1
        for t in range(t_bins):
            is_valid = bool(valid_bin_mask[tr, t])
            img = int(image_ids[tr, t]) if is_valid else -1
            if is_valid and run_len > 0 and img == prev_img:
                run_len += 1
            elif is_valid:
                if run_len > 0:
                    run_lengths.append(run_len)
                run_len = 1
            else:
                if run_len > 0:
                    run_lengths.append(run_len)
                    run_len = 0
            prev_img = img if is_valid else -1
        if run_len > 0:
            run_lengths.append(run_len)
    return np.asarray(run_lengths, dtype=np.int64)


def _pct(x: np.ndarray, q: float) -> float:
    if x.size == 0:
        return float("nan")
    return float(np.percentile(x, q))


def _nanmean_safe(arr: np.ndarray, axis: int) -> np.ndarray:
    valid = np.isfinite(arr)
    num = np.sum(np.where(valid, arr, 0.0), axis=axis)
    den = np.sum(valid, axis=axis)
    return np.divide(num, np.maximum(den, 1), out=np.full_like(num, np.nan, dtype=np.float64), where=den > 0)


def _compute_stage0_readiness(
    data: dict[str, object],
    requested_bin_ms: int,
) -> tuple[dict[str, object], dict[str, object]]:
    _validate_required_keys(data)
    robs = np.asarray(data["robs"], dtype=np.float32)  # (NT, T, NC)
    eyepos = np.asarray(data["eyepos"], dtype=np.float32)  # (NT, T, 2)
    image_ids = np.asarray(data["image_ids"], dtype=np.int64)  # (NT, T)
    fix_dur = np.asarray(data["fix_dur"], dtype=np.float32)  # (NT,)
    _validate_shapes(robs, eyepos, image_ids, fix_dur)

    inferred_bin_ms, inferred_bin_source = _infer_bin_ms(data, requested_bin_ms=requested_bin_ms)
    bin_s = max(inferred_bin_ms / 1000.0, 1e-6)

    nt, t_bins, n_units = robs.shape

    robs_valid = np.isfinite(robs).all(axis=2)
    eye_valid = np.isfinite(eyepos).all(axis=2)
    image_valid = image_ids >= 0
    valid_bin_mask = robs_valid & eye_valid & image_valid

    valid_bin_fraction = float(valid_bin_mask.mean())
    mean_fix_dur_bins = _safe_mean(fix_dur)

    # Count image-time support for leave-one-trial-out residual stability.
    repeat_counts = []
    for t in range(t_bins):
        ids_t = image_ids[:, t]
        valid_t = valid_bin_mask[:, t]
        if not np.any(valid_t):
            continue
        unique_ids, counts = np.unique(ids_t[valid_t], return_counts=True)
        for _img, c in zip(unique_ids, counts):
            repeat_counts.append(int(c))
    repeat_counts_arr = np.asarray(repeat_counts, dtype=np.int64)

    frac_image_time_cells_ge_2 = float(np.mean(repeat_counts_arr >= 2)) if repeat_counts_arr.size else float("nan")
    frac_image_time_cells_ge_3 = float(np.mean(repeat_counts_arr >= 3)) if repeat_counts_arr.size else float("nan")
    frac_image_time_cells_ge_5 = float(np.mean(repeat_counts_arr >= 5)) if repeat_counts_arr.size else float("nan")

    valid_image_ids = image_ids[valid_bin_mask]
    unique_images = np.unique(valid_image_ids) if valid_image_ids.size else np.asarray([], dtype=np.int64)
    if valid_image_ids.size:
        _uimg, image_counts = np.unique(valid_image_ids, return_counts=True)
        n_repeated_images = int(np.sum(image_counts >= 2))
    else:
        n_repeated_images = 0

    # Drift-step candidates: consecutive valid bins with stable image id.
    same_image_consecutive = image_ids[:, 1:] == image_ids[:, :-1]
    valid_consecutive = valid_bin_mask[:, 1:] & valid_bin_mask[:, :-1]
    valid_consecutive_count = int(np.sum(valid_consecutive))
    drift_step_candidates = int(np.sum(valid_consecutive & same_image_consecutive))

    eye_steps = np.linalg.norm(eyepos[:, 1:, :] - eyepos[:, :-1, :], axis=2)
    eye_steps_valid = eye_steps[valid_consecutive]
    eye_speeds_valid = eye_steps_valid / bin_s

    run_lengths = _collect_same_image_run_lengths(valid_bin_mask, image_ids)

    robs_valid_3d = np.isfinite(robs)
    n_valid_unit_bins = int(np.sum(robs_valid_3d))
    valid_robs_values = robs[robs_valid_3d]
    mean_response_per_valid_bin = _safe_mean(valid_robs_values)
    frac_zero_response_bins = float(np.mean(valid_robs_values <= 0.0)) if valid_robs_values.size else float("nan")
    median_response_per_valid_bin = float(np.median(valid_robs_values)) if valid_robs_values.size else float("nan")

    unit_valid_bins = np.sum(robs_valid_3d, axis=(0, 1)).astype(np.float64)
    unit_sum = np.nansum(robs, axis=(0, 1), dtype=np.float64)
    with np.errstate(invalid="ignore", divide="ignore"):
        unit_mean_per_bin = unit_sum / np.maximum(unit_valid_bins, 1.0)
    unit_est_rate_hz = unit_mean_per_bin / bin_s

    readiness = {
        "n_trials": int(nt),
        "n_bins": int(t_bins),
        "n_units": int(n_units),
        "requested_bin_ms": float(requested_bin_ms),
        "inferred_bin_ms": float(inferred_bin_ms),
        "bin_ms_source": inferred_bin_source,
        "mean_fixation_duration_bins": mean_fix_dur_bins,
        "valid_bin_fraction": valid_bin_fraction,
        "fraction_consecutive_valid_bins": float(valid_consecutive.mean()),
        "fraction_same_image_among_valid_consecutive": (
            float(drift_step_candidates / valid_consecutive_count) if valid_consecutive_count > 0 else float("nan")
        ),
        "drift_step_candidates": drift_step_candidates,
        "n_image_time_cells": int(repeat_counts_arr.size),
        "frac_image_time_cells_ge_2": frac_image_time_cells_ge_2,
        "frac_image_time_cells_ge_3": frac_image_time_cells_ge_3,
        "frac_image_time_cells_ge_5": frac_image_time_cells_ge_5,
        "median_repeat_count_per_image_time_cell": float(np.median(repeat_counts_arr)) if repeat_counts_arr.size else float("nan"),
        "p10_repeat_count_per_image_time_cell": _pct(repeat_counts_arr, 10.0),
        "p90_repeat_count_per_image_time_cell": _pct(repeat_counts_arr, 90.0),
        "n_unique_images": int(unique_images.size),
        "n_repeated_images": int(n_repeated_images),
        "eye_step_deg_median": float(np.median(eye_steps_valid)) if eye_steps_valid.size else float("nan"),
        "eye_step_deg_p90": _pct(eye_steps_valid, 90.0),
        "eye_step_deg_p99": _pct(eye_steps_valid, 99.0),
        "eye_speed_deg_s_median": float(np.median(eye_speeds_valid)) if eye_speeds_valid.size else float("nan"),
        "eye_speed_deg_s_p90": _pct(eye_speeds_valid, 90.0),
        "eye_speed_deg_s_p99": _pct(eye_speeds_valid, 99.0),
        "median_same_image_run_length_bins": float(np.median(run_lengths)) if run_lengths.size else float("nan"),
        "p90_same_image_run_length_bins": _pct(run_lengths, 90.0),
        "n_same_image_runs_ge_5_bins": int(np.sum(run_lengths >= 5)),
        "n_same_image_runs_ge_8_bins": int(np.sum(run_lengths >= 8)),
        "n_same_image_runs_ge_10_bins": int(np.sum(run_lengths >= 10)),
        "n_same_image_runs_ge_15_bins": int(np.sum(run_lengths >= 15)),
        "n_valid_unit_bins": n_valid_unit_bins,
        "mean_response_per_valid_bin": mean_response_per_valid_bin,
        "median_response_per_valid_bin": median_response_per_valid_bin,
        "frac_zero_response_bins": frac_zero_response_bins,
        "median_unit_est_rate_hz": float(np.nanmedian(unit_est_rate_hz)) if unit_est_rate_hz.size else float("nan"),
        "p90_unit_est_rate_hz": _pct(unit_est_rate_hz[np.isfinite(unit_est_rate_hz)], 90.0),
        "n_units_est_rate_ge_0_5_hz": int(np.sum(unit_est_rate_hz >= 0.5)),
        "n_units_est_rate_ge_1_0_hz": int(np.sum(unit_est_rate_hz >= 1.0)),
        "n_units_est_rate_ge_2_0_hz": int(np.sum(unit_est_rate_hz >= 2.0)),
    }

    proceed_checks = {
        "valid_bin_fraction": bool(readiness["valid_bin_fraction"] >= 0.5),
        "same_image_runs_ge_10": bool(readiness["n_same_image_runs_ge_10_bins"] >= 50),
        "repeat_support_ge_3": bool(readiness["frac_image_time_cells_ge_3"] >= 0.2),
        "units_ge_1hz": bool(readiness["n_units_est_rate_ge_1_0_hz"] >= 20),
    }
    fallback_checks = {
        "very_low_valid_fraction": bool(readiness["valid_bin_fraction"] < 0.2),
        "very_low_run_support": bool(readiness["n_same_image_runs_ge_8_bins"] < 20),
        "very_low_repeat_support": bool(readiness["frac_image_time_cells_ge_2"] < 0.1),
        "very_low_unit_support": bool(readiness["n_units_est_rate_ge_0_5_hz"] < 10),
    }

    if all(proceed_checks.values()):
        recommendation = "proceed"
    elif any(fallback_checks.values()):
        recommendation = "fallback"
    else:
        recommendation = "needs_review"

    meta = {
        "proceed_checks": proceed_checks,
        "fallback_checks": fallback_checks,
        "recommendation": recommendation,
        "thresholds": {
            "valid_bin_fraction_min": 0.5,
            "n_same_image_runs_ge_10_bins_min": 50,
            "frac_image_time_cells_ge_3_min": 0.2,
            "n_units_est_rate_ge_1_0_hz_min": 20,
            "fallback_valid_bin_fraction_lt": 0.2,
            "fallback_n_same_image_runs_ge_8_bins_lt": 20,
            "fallback_frac_image_time_cells_ge_2_lt": 0.1,
            "fallback_n_units_est_rate_ge_0_5_hz_lt": 10,
        },
    }
    return readiness, meta


